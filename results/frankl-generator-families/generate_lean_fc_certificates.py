#!/usr/bin/env python3
"""Propose finite FC-family search trees for independent Lean checking.

The search follows the closed-extension/share method of Maric, Zivkovic,
and Vuckovic, arXiv:1207.3604.  Python output is never a proof: each emitted
module contains an ordinary kernel-reduced check of the full certificate,
followed by the proved verifier-soundness theorem.
"""

from __future__ import annotations

import argparse
from functools import lru_cache
from pathlib import Path


PATTERNS = {
    "triangle": (4, (7, 11, 13), (1, 1, 1, 1)),
    "star": (5, (7, 11, 19), (3, 3, 2, 2, 2)),
    "path": (5, (7, 13, 25), (6, 3, 5, 5, 3)),
    "path_edge": (6, (7, 13, 49), (12, 7, 9, 7, 6, 6)),
    "matching": (7, (7, 25, 97), (2, 1, 1, 1, 1, 1, 1)),
    "pasch": (6, (7, 25, 44, 50), (1, 1, 1, 1, 1, 1)),
}


def elements(mask: int):
    while mask:
        bit = mask & -mask
        mask -= bit
        yield bit.bit_length() - 1


def unions(generators):
    result = {0}
    for g in generators:
        result |= {s | g for s in result}
    return tuple(sorted(result - {0}))


def propose(n, generators, weights, limit):
    base = unions(generators)
    shares = tuple(
        sum((1 if s >> i & 1 else -1) * w for i, w in enumerate(weights))
        for s in range(1 << n)
    )
    negatives = tuple(sorted(
        (s for s in range(1 << n) if shares[s] < 0),
        key=lambda s: (shares[s], s),
    ))
    negative_mask = sum(1 << s for s in negatives)
    nodes = [None]
    intern = {}
    calls = 0

    @lru_cache(maxsize=200000)
    def total(family):
        return sum(shares[s] for s in elements(family))

    def search(forced, excluded, pos):
        nonlocal calls
        calls += 1
        if calls > limit:
            raise RuntimeError(f"search exceeded {limit} nodes")
        if forced & excluded:
            return 0
        remaining = negative_mask & ~(forced | excluded)
        if total(forced) + total(remaining) >= 0:
            return 0
        while pos < len(negatives) and (forced | excluded) >> negatives[pos] & 1:
            pos += 1
        if pos == len(negatives):
            raise RuntimeError(f"negative-share extension: {list(elements(forced))}")
        a = negatives[pos]
        absent = search(forced, excluded | (1 << a), pos + 1)
        enlarged = forced | (1 << a)
        for b in elements(forced):
            enlarged |= 1 << (a | b)
        for b in base:
            enlarged |= 1 << (a | b)
        present = search(enlarged, excluded, pos + 1)
        key = (a, absent, present)
        if key not in intern:
            intern[key] = len(nodes)
            nodes.append(key)
        return intern[key]

    root = search(0, 0, 0)
    return base, nodes, root, calls


def lean_set(mask):
    items = list(elements(mask))
    return "∅" if not items else "{" + ", ".join(map(str, items)) + "}"


def emit(name, n, generators, weights, base, nodes, root, calls):
    title = "".join(part.title() for part in name.split("_"))
    lines = [
        "import Conjectures.FranklFC",
        "",
        "set_option maxRecDepth 20000",
        "set_option maxHeartbeats 0",
        "set_option Elab.async false",
        "",
        f"namespace Frankl.FC.Vaughan{title}",
        "",
        f"/-! Generated by generate_lean_fc_certificates.py; {calls} search visits.",
        "The certificate is checked below with ordinary kernel reduction. -/",
        "",
        f"def ground : Finset ℕ := Finset.range {n}",
        f"def weights (i : ℕ) : ℕ := ({list(weights)} : List ℕ).getD i 0",
        "def base : Finset (Finset ℕ) := {" + ", ".join(map(lean_set, base)) + "}",
        "",
        "private def c0 : ShareSearch.Certificate (Finset ℕ) := .leaf",
    ]
    for i, (a, absent, present) in enumerate(nodes[1:], 1):
        lines.append(
            f"private def c{i} : ShareSearch.Certificate (Finset ℕ) := "
            f".split ({lean_set(a)} : Finset ℕ) c{absent} c{present}"
        )
    lines.extend([
        "",
        f"def certificate : ShareSearch.Certificate (Finset ℕ) := c{root}",
        "",
        "theorem checked :",
        "    ShareSearch.check (fun A B => A ∪ B) base ground.powerset",
        "      (share ground weights) ∅ ∅ certificate = true := by",
        "  decide +kernel",
        "",
        "theorem extension_share_nonnegative {family : Finset (Finset ℕ)}",
        "    (hc : ShareSearch.ClosedFor (fun A B => A ∪ B) base family)",
        "    (hd : family ⊆ ground.powerset) :",
        "    0 ≤ ∑ S ∈ family, share ground weights S :=",
        "  ShareSearch.certificate_nonnegative certificate checked hc hd",
        "",
        "theorem abundant {family : Finset (Finset ℕ)}",
        "    (hu : UnionClosed family) (hb : base ⊆ family) :",
        "    ∃ x ∈ ground, 0 < weights x ∧ Abundant family x := by",
        "  exact abundant_of_certificate hu hb (by decide +kernel)",
        "    (by refine ⟨0, ?_, ?_⟩ <;> decide +kernel) certificate checked",
        "",
        f"end Frankl.FC.Vaughan{title}",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pattern", choices=PATTERNS)
    parser.add_argument("--node-limit", type=int, default=10000000)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    n, generators, weights = PATTERNS[args.pattern]
    base, nodes, root, calls = propose(n, generators, weights, args.node_limit)
    output = args.output or Path(__file__).resolve().parents[2] / "lean" / "Conjectures" / (
        "FranklVaughan" + "".join(p.title() for p in args.pattern.split("_")) + ".lean"
    )
    output.write_text(emit(args.pattern, n, generators, weights, base, nodes, root, calls))
    print(f"{output.name}: {calls} visits, {len(nodes)} distinct certificate nodes")


if __name__ == "__main__":
    main()
