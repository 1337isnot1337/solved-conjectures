#!/usr/bin/env python3
"""Pilot contiguous C intervals with a bounded number of unchanged D checks.

This uses the original cache generator, predicates, interval-append theorem,
base assembly, normalized-cover bridge, and global-cover bridge. Only the
proof interval layout and generated declaration names differ.
"""
from __future__ import annotations

from argparse import ArgumentParser
from hashlib import sha256
import json
from pathlib import Path

import generate_lean_root_quick as original


MARKER = "-- Generated by generate_lean_root_cblock_budget.py; all finite checks require the Lean kernel.\n"


class BudgetGenerator(original.Generator):
    def __init__(self, prime: int, lean_dir: Path, budget: int, bases_per_module: int):
        super().__init__(prime, lean_dir, 32, 16, 16, False, bases_per_module)
        if budget < 1:
            raise ValueError("A positive C-D work budget is required")
        self.budget = budget
        self.ns = f"Loneliness.FiveSpeedCertificate.RootCBlockCertificates.P{prime}B{budget}"
        self.stem = f"LonelinessFiveSpeedRootCBlockP{prime:04d}B{budget}"
        self.data_module = f"LonelinessFiveSpeedRootCBlockDataP{prime:04d}B{budget}"
        self.data_ns = self.ns + ".Data"
        self.intervals = []

    def base(self, b: int) -> str:
        module = self.stem + f"B{b:04d}"
        namespace = self.ns + f".B{b:04d}"
        lines = original.header([
            "LonelinessFiveSpeedRootQuickChunkAssembly", self.data_module,
            f"LonelinessFiveSpeedPackedScalar{self.p}"], namespace)
        costs = [0] * (self.n + 1)
        for index, c in enumerate(self.values[b]):
            if self.nontrivial_c(b, c):
                costs[c] = len(self.values[b]) - index - 1
        if max(costs) > self.budget:
            raise ValueError("One complete C row exceeds this pilot's work budget")
        spans = []
        start = 0
        work = 0
        for c, cost in enumerate(costs):
            if c > start and work + cost > self.budget:
                spans.append((start, c - start, work))
                start, work = c, 0
            work += cost
        spans.append((start, self.n + 1 - start, work))
        if (spans[0][0] != 0 or sum(count for _, count, _ in spans) != self.n + 1
                or any(count < 1 or work > self.budget for _, count, work in spans)):
            raise ValueError("Internal interval layout mismatch")
        intervals = []
        for start, count, work in spans:
            name = f"checkedC{start:04d}"
            lines.extend([
                f"theorem {name} : rootQuickBlockCheck {self.q_arguments(b)} "
                f"{start} {count} = true := by\n",
                "  decide +kernel\n\n",
            ])
            intervals.append(original.Block(start, count, name))
            self.intervals.append({"base": b, "start": start, "count": count,
                                   "cd_prefixes": work})
            self.finite_leaf_count += 1
            self.c_leaf_count += 1
        combined = original.balanced_blocks(intervals,
            "rootQuickBlockCheck_append " + self.q_arguments(b))
        if combined.start != 0 or combined.count != self.n + 1:
            raise ValueError("Complete C interval was not recovered")
        lines.extend([
            f"theorem checked : rootQuickBlockCheck {self.q_arguments(b)} "
            f"0 {self.n + 1} = true :=\n  {combined.proof}\n\n",
            f"theorem base_checked : rootQuickBaseBlockCheck {self.p} {self.G} {self.inv}\n",
            f"    {self.flag} Data.values Data.eligible {b} 1 = true :=\n",
            f"  rootQuickBaseBlockCheck_of_cblock {self.p} {self.G} {self.inv}\n",
            f"    {self.flag} Data.values Data.eligible {b} checked\n\n",
            f"end {namespace}\n",
        ])
        self.sources[module] = "".join(lines)
        self.required.append(namespace + ".base_checked")
        return module

    def build(self) -> None:
        super().build()
        self.sources = {module: source.replace(original.MARKER, MARKER, 1)
                        for module, source in self.sources.items()}


def main() -> None:
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--prime", type=int, default=199)
    parser.add_argument("--budget", type=int, default=4096)
    parser.add_argument("--bases-per-module", type=int, default=4)
    parser.add_argument("--lean-dir", type=Path, required=True)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--manifest", type=Path)
    args = parser.parse_args()
    generator = BudgetGenerator(args.prime, args.lean_dir, args.budget, args.bases_per_module)
    generator.build()
    records = []
    for module, source in generator.sources.items():
        target = args.lean_dir / (module + ".lean")
        raw = source.encode()
        if args.write:
            if target.exists() and target.read_bytes() != raw:
                raise ValueError("An existing source differs from this pilot: " + str(target))
            target.write_bytes(raw)
        records.append({"module": "Conjectures." + module,
                        "source_sha256": sha256(raw).hexdigest(), "source_bytes": len(raw)})
    manifest = {
        "status": "untrusted candidate layout; fresh Lean source/audit/kernel gates are separate",
        "prime": args.prime, "budget": args.budget, "bases_per_module": args.bases_per_module,
        "use_prefix": False, "modules": records, "module_count": len(records),
        "source_bytes": sum(row["source_bytes"] for row in records),
        "required": generator.required, "base_parts": generator.base_parts,
        "finite_leaf_count": generator.finite_leaf_count,
        "c_leaf_count": generator.c_leaf_count, "d_leaf_count": generator.d_leaf_count,
        "cd_prefix_count": sum(row["cd_prefixes"] for row in generator.intervals),
        "intervals": generator.intervals,
        "scalar_source_sha256": generator.scalar_sha256,
        "original_generator_sha256": sha256(Path(original.__file__).read_bytes()).hexdigest(),
        "generator_sha256": sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    if args.manifest:
        args.manifest.write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({key: value for key, value in manifest.items()
                      if key not in {"modules", "required", "intervals", "base_parts"}}, indent=2))


if __name__ == "__main__":
    main()
