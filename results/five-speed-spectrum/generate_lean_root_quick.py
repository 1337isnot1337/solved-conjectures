#!/usr/bin/env python3
"""Generate exact cached root checks with bounded D lists and balanced assembly.

The generated proof does not trust this program's cache construction or its
choice of chunks. Literal caches are compared with the original definitions;
every finite leaf is checked by Lean's kernel; append lemmas recover complete
C and base intervals. Existing root generators and generic checks are untouched.
"""
from __future__ import annotations

from argparse import ArgumentParser
from dataclasses import dataclass
from hashlib import sha256
import json
from pathlib import Path
import re


MARKER = '-- Generated by generate_lean_root_quick.py; all finite checks require the Lean kernel.\n'


def lean_list(values: list[int]) -> str:
    return '[' + ', '.join(map(str, values)) + ']'


def chunks(values: list[int], size: int) -> list[list[int]]:
    return [values[start:start + size] for start in range(0, len(values), size)]


def header(imports: list[str], namespace: str) -> list[str]:
    return [MARKER, *(f'import Conjectures.{name}\n' for name in imports),
            '\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n',
            'set_option Elab.async false\n\n', f'namespace {namespace}\n\n']


@dataclass(frozen=True)
class Block:
    start: int
    count: int
    proof: str


def balanced_blocks(blocks: list[Block], append_prefix: str) -> Block:
    assert blocks and all(a.start + a.count == b.start for a, b in zip(blocks, blocks[1:]))
    if len(blocks) == 1:
        return blocks[0]
    middle = len(blocks) // 2
    left = balanced_blocks(blocks[:middle], append_prefix)
    right = balanced_blocks(blocks[middle:], append_prefix)
    proof = (f'({append_prefix} {left.start} {left.count} {right.count}\n'
             f'    {left.proof}\n    {right.proof})')
    return Block(left.start, left.count + right.count, proof)


def balanced_lists(proofs: list[tuple[str, str]], append_prefix: str) -> tuple[str, str]:
    """Keep list arguments explicit, so elaboration does not infer them by reduction."""
    assert proofs
    if len(proofs) == 1:
        return proofs[0]
    middle = len(proofs) // 2
    left_list, left_proof = balanced_lists(proofs[:middle], append_prefix)
    right_list, right_proof = balanced_lists(proofs[middle:], append_prefix)
    return (f'({left_list} ++ {right_list})',
            f'({append_prefix} {left_list} {right_list}\n    {left_proof}\n    {right_proof})')


class Generator:
    def __init__(self, prime: int, lean_dir: Path, d_chunk: int, c_chunk: int,
                 base_chunk: int, use_prefix: bool, bases_per_module: int) -> None:
        if prime < 3 or prime % 2 == 0 or min(d_chunk, c_chunk, base_chunk, bases_per_module) < 1:
            raise ValueError('positive chunks and an odd modulus at least three are required')
        self.p, self.n = prime, prime // 2
        self.lean_dir = lean_dir
        self.d_chunk, self.c_chunk, self.base_chunk = d_chunk, c_chunk, base_chunk
        self.bases_per_module = bases_per_module
        self.flag = 'true' if use_prefix else 'false'
        self.scalar = f'ScalarTrees.P{prime}'
        self.G = f'PackedScalars.P{prime}.mask'
        self.inv = f'(treeInverse {self.scalar}.tree)'
        self.ns = f'Loneliness.FiveSpeedCertificate.RootQuickCertificates.P{prime}'
        self.stem = f'LonelinessFiveSpeedRootQuickP{prime:04d}'
        self.data_module = f'LonelinessFiveSpeedRootQuickDataP{prime:04d}'
        self.data_ns = f'{self.ns}.Data'
        self.scalar_path = lean_dir / f'LonelinessFiveSpeedScalarTreeMask{prime:04d}.lean'
        scalar_bytes = self.scalar_path.read_bytes()
        entries = re.findall(r'inverse := (\d+), mask := (0x[0-9a-fA-F]+)', scalar_bytes.decode())
        if len(entries) != self.n:
            raise ValueError('unexpected number of literal scalar entries')
        self.inverses = [0] + [int(inv) for inv, _ in entries]
        self.masks = [0] + [int(mask, 16) for _, mask in entries]
        for a in range(1, self.n + 1):
            if a * self.inverses[a] % prime != 1:
                raise ValueError(f'invalid inverse in source at multiplier {a}')
            if not 0 <= self.masks[a] < (1 << prime):
                raise ValueError(f'mask outside p bits at multiplier {a}')
        self.scalar_sha256 = sha256(scalar_bytes).hexdigest()
        self.values = [[x for x in range(self.n + 1) if self.eligible(b, x)]
                       for b in range(self.n + 1)]
        self.eligible_masks = [sum(1 << x for x in values) for values in self.values]
        self.sources: dict[str, str] = {}
        self.required: list[str] = []
        self.finite_leaf_count = 0
        self.d_leaf_count = 0
        self.c_leaf_count = 0
        self.split_rows = 0
        self.base_parts: list[dict[str, object]] = []

    def fold(self, value: int) -> int:
        residue = value % self.p
        return min(residue, self.p - residue)

    def ratio(self, x: int, y: int) -> int:
        return min(self.fold(self.inverses[x] * y), self.fold(self.inverses[y] * x))

    def eligible(self, b: int, x: int) -> bool:
        return b < x and b <= self.ratio(1, x) and b <= self.ratio(b, x)

    def base_active(self, b: int) -> bool:
        return 2 <= b <= self.n and b <= self.ratio(1, b)

    @staticmethod
    def cheap_c(b: int, c: int) -> bool:
        return b == 2 and c in (3, 4) or b == 3 and c == 4

    def nontrivial_c(self, b: int, c: int) -> bool:
        return (self.base_active(b) and c in self.values[b] and not self.cheap_c(b, c)
                and any(d > c for d in self.values[b]))

    def needs_module(self, b: int) -> bool:
        return any(self.nontrivial_c(b, c) for c in range(self.n + 1))

    def data(self) -> None:
        lines = header(['LonelinessFiveSpeedRootStar',
                        f'LonelinessFiveSpeedScalarTreeMask{self.p:04d}'], self.data_ns)
        for b, values in enumerate(self.values):
            suffix = f'{b:04d}'
            lines.extend([
                f'noncomputable def values{suffix} : List ℕ := {lean_list(values)}\n',
                f'noncomputable def eligible{suffix} : ℕ := 0x{self.eligible_masks[b]:x}\n\n',
                f'theorem values_checked{suffix} : values{suffix} =\n',
                f'    rootStarValues {self.p} {self.inv} {b} := by\n  decide +kernel\n\n',
                f'theorem eligible_checked{suffix} : eligible{suffix} =\n',
                f'    rootStarEligibleMask {self.p} {self.inv} {b} := by\n  decide +kernel\n\n',
            ])
        for name, result_type, default in [('values', 'List ℕ', '[]'), ('eligible', 'ℕ', '0')]:
            lines.append(f'noncomputable def {name} : ℕ → {result_type}\n')
            lines.extend(f'  | {b} => {name}{b:04d}\n' for b in range(self.n + 1))
            lines.append(f'  | _ => {default}\n\n')
        for name, original in [('values', 'rootStarValues'), ('eligible', 'rootStarEligibleMask')]:
            lines.extend([
                f'theorem {name}_checked : ∀ b, b ≤ {self.p} / 2 →\n',
                f'    {name} b = {original} {self.p} {self.inv} b := by\n',
                f'  have h : ∀ b : Fin {self.n + 1},\n',
                f'      {name} b.val = {original} {self.p} {self.inv} b.val := by\n',
                '    intro b\n    fin_cases b\n',
            ])
            lines.extend(f'    · exact {name}_checked{b:04d}\n' for b in range(self.n + 1))
            lines.extend(['  intro b hb\n  exact h ⟨b, by omega⟩\n\n'])
            self.required.append(f'{self.data_ns}.{name}_checked')
        lines.append(f'end {self.data_ns}\n')
        self.sources[self.data_module] = ''.join(lines)

    def q_arguments(self, b: int) -> str:
        return (f'{self.p} {self.G} {self.inv} {self.flag} {b}\n'
                f'    Data.values{b:04d} Data.eligible{b:04d}')

    def d_arguments(self, b: int, c: int) -> str:
        return (f'{self.p} {self.G} (rootStarListLeaf {self.p})\n'
                f'    (rootQuickPrefixCheck {self.p} {self.flag}) {b} {c} Data.eligible{b:04d}')

    def base(self, b: int) -> str:
        module = self.stem + f'B{b:04d}'
        namespace = self.ns + f'.B{b:04d}'
        lines = header(['LonelinessFiveSpeedRootQuickChunkAssembly', self.data_module,
                        f'LonelinessFiveSpeedPackedScalar{self.p}'], namespace)
        intervals: list[Block] = []
        c = 0
        while c <= self.n:
            if self.nontrivial_c(b, c):
                count = 1
            else:
                count = 1
                while (count < self.c_chunk and c + count <= self.n
                       and not self.nontrivial_c(b, c + count)):
                    count += 1
            name = f'checkedC{c:04d}'
            tail = [d for d in self.values[b] if d > c]
            if self.nontrivial_c(b, c) and len(tail) > self.d_chunk:
                self.split_rows += 1
                front = [d for d in self.values[b] if d <= c]
                d_lists = ([front] if front else []) + chunks(tail, self.d_chunk)
                assert sum(d_lists, []) == self.values[b]
                d_proofs = []
                for index, ds in enumerate(d_lists):
                    d_name = f'dataC{c:04d}D{index:04d}'
                    proof_name = f'checkedC{c:04d}D{index:04d}'
                    lines.extend([
                        f'noncomputable def {d_name} : List ℕ := {lean_list(ds)}\n\n',
                        f'theorem {proof_name} : rootStarCachedAcceptedDCheck\n',
                        f'    {self.d_arguments(b, c)} {d_name} = true := by\n',
                        '  decide +kernel\n\n',
                    ])
                    d_proofs.append((d_name, proof_name))
                    self.finite_leaf_count += 1
                    self.d_leaf_count += 1
                combined_list, combined_proof = balanced_lists(d_proofs,
                    'rootStarCachedAcceptedDCheck_append_true ' + self.d_arguments(b, c))
                lines.extend([
                    f'theorem {name} : rootQuickBlockCheck {self.q_arguments(b)} {c} 1 = true := by\n',
                    f'  refine rootQuickBlockCheck_singleton_of_dcheck {self.q_arguments(b)} {c} ?_\n',
                    f'  have hvalues : Data.values{b:04d} = {combined_list} := rfl\n',
                    '  rw [hvalues]\n',
                    f'  exact {combined_proof}\n\n',
                ])
            else:
                lines.extend([
                    f'theorem {name} : rootQuickBlockCheck {self.q_arguments(b)} {c} {count} = true := by\n',
                    '  decide +kernel\n\n',
                ])
                self.finite_leaf_count += 1
                self.c_leaf_count += 1
            intervals.append(Block(c, count, name))
            c += count
        combined = balanced_blocks(intervals, 'rootQuickBlockCheck_append ' + self.q_arguments(b))
        assert combined.start == 0 and combined.count == self.n + 1
        lines.extend([
            f'theorem checked : rootQuickBlockCheck {self.q_arguments(b)} 0 {self.n + 1} = true :=\n',
            f'  {combined.proof}\n\n',
            f'theorem base_checked : rootQuickBaseBlockCheck {self.p} {self.G} {self.inv}\n',
            f'    {self.flag} Data.values Data.eligible {b} 1 = true :=\n',
            f'  rootQuickBaseBlockCheck_of_cblock {self.p} {self.G} {self.inv}\n',
            f'    {self.flag} Data.values Data.eligible {b} checked\n\n',
            f'end {namespace}\n',
        ])
        self.sources[module] = ''.join(lines)
        self.required.append(namespace + '.base_checked')
        return module

    def assembly(self) -> None:
        active = [b for b in range(self.n + 1) if self.needs_module(b)]
        modules = [self.base(b) for b in active]
        if self.bases_per_module > 1:
            grouped_modules = []
            for part, offset in enumerate(range(0, len(modules), self.bases_per_module)):
                selected = modules[offset:offset + self.bases_per_module]
                sources = [self.sources.pop(module) for module in selected]
                prefix = sources[0].split('\nnamespace ', 1)[0]
                bodies = ['namespace ' + source.split('\nnamespace ', 1)[1] for source in sources]
                module = self.stem + f'Part{part:02d}'
                self.sources[module] = prefix + '\n\n' + '\n'.join(bodies)
                grouped_modules.append(module)
                self.base_parts.append({'module': 'Conjectures.' + module,
                                        'bases': active[offset:offset + self.bases_per_module]})
            modules = grouped_modules
        else:
            self.base_parts = [{'module': 'Conjectures.' + module, 'bases': [b]}
                               for module, b in zip(modules, active)]
        lines = header(['LonelinessFiveSpeedRootQuickChunkAssembly',
                        'LonelinessFiveSpeedRootSemantics', self.data_module,
                        f'LonelinessFiveSpeedPackedScalar{self.p}', *modules], self.ns)
        intervals: list[Block] = []
        b = 0
        base_arguments = (f'{self.p} {self.G} {self.inv}\n'
                          f'    {self.flag} Data.values Data.eligible')
        while b <= self.n:
            if b in active:
                intervals.append(Block(b, 1, f'B{b:04d}.base_checked'))
                b += 1
            else:
                count = 1
                while (count < self.base_chunk and b + count <= self.n
                       and b + count not in active):
                    count += 1
                name = f'checkedTrivialBase{b:04d}'
                lines.extend([
                    f'theorem {name} : rootQuickBaseBlockCheck {base_arguments} {b} {count} = true := by\n',
                    '  decide +kernel\n\n',
                ])
                intervals.append(Block(b, count, name))
                self.finite_leaf_count += 1
                b += count
        combined = balanced_blocks(intervals, 'rootQuickBaseBlockCheck_append ' + base_arguments)
        assert combined.start == 0 and combined.count == self.n + 1
        lines.extend([
            f'theorem checked : rootQuickBaseBlockCheck {base_arguments} 0 {self.n + 1} = true :=\n',
            f'  {combined.proof}\n\n',
            f'theorem normalized : Loneliness.FiveSpeedRoot.NormalizedRootCover {self.p} {self.inv} :=\n',
            f'  normalizedRootCover_of_rootQuickBaseBlocks {self.p} (by decide) {self.G} {self.inv}\n',
            f'    {self.flag} Data.values Data.eligible PackedScalars.P{self.p}.sound\n',
            '    Data.values_checked Data.eligible_checked checked\n\n',
            f'theorem sound : Loneliness.FiveSpeedRoot.GlobalRootCover {self.p} :=\n',
            f'  Loneliness.FiveSpeedRoot.rootCover_of_normalized {self.p} (by decide) {self.inv}\n',
            f'    (scalarTreeCheck_inverse {self.p} {self.scalar}.tree {self.scalar}.checked) normalized\n\n',
            f'end {self.ns}\n',
        ])
        self.sources[self.stem] = ''.join(lines)
        self.required.extend(self.ns + '.' + name for name in ['checked', 'normalized', 'sound'])

    def build(self) -> None:
        self.data()
        self.assembly()


def main() -> None:
    parser = ArgumentParser(description=__doc__)
    parser.add_argument('--prime', type=int, required=True)
    parser.add_argument('--lean-dir', type=Path, required=True)
    parser.add_argument('--d-chunk', type=int, default=32)
    parser.add_argument('--c-chunk', type=int, default=16)
    parser.add_argument('--base-chunk', type=int, default=16)
    parser.add_argument('--bases-per-module', type=int, default=1)
    parser.add_argument('--use-prefix', action='store_true')
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--manifest', type=Path)
    args = parser.parse_args()
    generator = Generator(args.prime, args.lean_dir, args.d_chunk, args.c_chunk,
                          args.base_chunk, args.use_prefix, args.bases_per_module)
    generator.build()
    records = []
    for module, source in generator.sources.items():
        destination = args.lean_dir / (module + '.lean')
        if args.write:
            if destination.exists() and not destination.read_text().startswith(MARKER):
                raise RuntimeError(f'refusing to overwrite a source not owned by this generator: {destination}')
            destination.write_text(source)
        raw = source.encode()
        records.append(dict(module='Conjectures.' + module,
                            source_sha256=sha256(raw).hexdigest(), source_bytes=len(raw)))
    result = dict(status=('candidate source written; Lean source, axiom and independent kernel gates pending'
                          if args.write else 'dry-run candidate only; no source written'),
                  prime=args.prime, modules=records, module_count=len(records),
                  source_bytes=sum(record['source_bytes'] for record in records),
                  required=generator.required, scalar_source_sha256=generator.scalar_sha256,
                  generator_sha256=sha256(Path(__file__).read_bytes()).hexdigest(),
                  d_chunk=args.d_chunk, c_chunk=args.c_chunk, base_chunk=args.base_chunk,
                  bases_per_module=args.bases_per_module, base_parts=generator.base_parts,
                  use_prefix=args.use_prefix,
                  finite_leaf_count=generator.finite_leaf_count,
                  d_leaf_count=generator.d_leaf_count, c_leaf_count=generator.c_leaf_count,
                  split_rows=generator.split_rows,
                  note='Literal cache comparisons and balanced append proofs check the complete intervals; Python choices are not assumptions.')
    if args.manifest:
        args.manifest.write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps({key: value for key, value in result.items() if key not in ['modules', 'required']}, indent=2))


if __name__ == '__main__':
    main()
