"""Generate exact interval certificates for the twelve recorded five-speed examples.

This script proposes data. The generated Lean file checks that the intervals
cover every real time and that a rational time attains the claimed value.
It does not certify the completeness of the list of exceptional quintuples.
"""

from fractions import Fraction
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXAMPLES = {
    (1, 2, 3, 5, 8): 2,
    (1, 3, 4, 5, 9): 1,
    (1, 3, 4, 5, 11): 3,
    (1, 3, 4, 5, 18): 2,
    (1, 3, 4, 5, 27): 6,
    (1, 4, 5, 6, 7): 2,
    (1, 4, 5, 6, 27): 6,
    (1, 7, 8, 9, 15): 3,
    (2, 3, 5, 8, 19): 4,
    (2, 5, 7, 8, 9): 3,
    (3, 5, 8, 9, 13): 4,
    (3, 5, 8, 11, 13): 4,
}


def rational(x):
    return str(x.numerator) if x.denominator == 1 else f"({x.numerator} / {x.denominator})"


def minimum_distance(speeds, t):
    phases = [(d * t) % 1 for d in speeds]
    return min(min(x, 1 - x) for x in phases)


def certificate(speeds, value):
    intervals = [
        (Fraction(k - value, d), Fraction(k + value, d), d, k)
        for d in speeds
        for k in range(d + 1)
    ]
    chain = []
    right = Fraction(0)
    while right < 1:
        available = [c for c in intervals if c[0] <= right < c[1]]
        if not available:
            raise ValueError(f"Upper bound fails for {speeds} at {right}")
        c = max(available, key=lambda c: c[1])
        chain.append(c)
        right = c[1]
    candidates = (
        Fraction(a, x + y)
        for x, y in combinations(speeds, 2)
        for a in range((x + y) // 2 + 1)
    )
    t = next(t for t in candidates if minimum_distance(speeds, t) == value)
    shifts = [(d * t).__floor__() for d in speeds]
    return chain, t, shifts


def main():
    lines = [
        "import Conjectures.Loneliness",
        "",
        "/-! Exact maxima for the twelve listed five-speed examples.",
        "The interval certificates prove upper bounds at every real time.",
        "This file does not assert that the list exhausts all exceptional sets.",
        "Generated by results/five-speed-spectrum/generate_lean_examples.py. -/",
        "",
        "namespace Loneliness.FiveSpeedExamples",
        "",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 4000000",
        "",
    ]
    for speeds, s in EXAMPLES.items():
        r = Fraction(s, 5 * s + 1)
        chain, t, shifts = certificate(speeds, r)
        name = "v" + "_".join(map(str, speeds))
        data = ",\n  ".join(
            f"⟨{rational(l)}, {rational(u)}, {d}, {k}⟩" for l, u, d, k in chain
        )
        lines.extend([
            f"def {name}Cover : List Segment := [",
            f"  {data}]",
            "",
            f"theorem {name}_value : value {list(speeds)} = ({rational(r)} : ℝ) := by",
            f"  have h := certified_value (ds := {list(speeds)}) (r := {rational(r)})",
            f"    (cs := {name}Cover) (t := {rational(t)}) (ks := {shifts})",
            f"    (by norm_num [{name}Cover, Segment.Valid])",
            f"    (by norm_num [{name}Cover, coversFrom])",
            "    (by norm_num [LowerCertificate]) (by norm_num) (by norm_num)",
            "  norm_num at h",
            "  exact h",
            "",
        ])
        print(f"{name}: value={r}, time={t}, covering intervals={len(chain)}")
    lines.extend(["end Loneliness.FiveSpeedExamples", ""])
    destination = ROOT / "lean/Conjectures/LonelinessFiveExamples.lean"
    destination.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
