# Group 6

def group_lemma2():
    n = 0
    for k in range(2, 9):
        for s in range(1, 5):
            D = list(range(1, k)) + [k * s]
            found, _ = exhaustive_colouring(D, k, k * s + 1)
            check(found is None, "Lemma 2: {1..%d,%d} has a proper %d-colouring of {0..%d}" % (k - 1, k * s, k, k * s))
            n += 1
    print("6. Lemma 2 on small cases: %d sets {1,...,k-1,ks} (2 <= k <= 8, 1 <= s <= 4) have no proper "
          "k-colouring of {0,...,ks}" % n)


def main():
    with open(os.path.join(HERE, "certificates.json")) as handle:
        cert = json.load(handle)
    for group in (group_tables, group_sporadic, group_exceptional, group_one_parameter,
                  group_two_parameter):
        try:
            group(cert)
        except Exception as error:          # a malformed certificate is a failure, not a crash
            check(False, "%s raised %r" % (group.__name__, error))
    group_lemma2()
    if FAILURES:
        print("FAILED: %d check(s) failed." % len(FAILURES))
        return 1
    print("All checks passed (65 tables, 62 colourings, 3 exceptional sets, 4 one-parameter families, "
          "334 two-parameter cases, Lemma 2 cases).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
