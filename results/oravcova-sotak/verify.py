#!/usr/bin/env python3
"""Check the certificates for "Distance graphs with maximum chromatic number".

Standard library only, exact integer and Fraction arithmetic, deterministic.
Reads certificates.json from the directory of this script.  Exit status 0 means
every check passed.  The groups follow the section "Verification" of PROOF.md.

1. Tables (input to the proof; R5-R8).  Each of the 12 + 9 + 27 + 17 = 65 listed
   sets is sorted, primitive and of size k; L(D) is recomputed exactly as the
   maximum of min_d ||d t|| over t = a/(d_i + d_j), i <= j, 0 <= a <= d_i + d_j
   (a local maximum of the minimum of tent functions is either the peak of one
   tent or a crossing of a rising and a falling tent, both of which are such
   times); it must equal the listed value and be below 1/k.  The five- and
   six-speed tables are compared with an independent transcription, typed into
   this file from results/{five,six}-speed-spectrum/PROOF.md.  The seven- and
   eight-speed tables are compared with ../../results/*/sporadic.txt when those
   files exist (otherwise a note is printed and that comparison is skipped).
2. Sporadic colourings ("Listed sets" in the proof of Theorem A).  Exactly the
   three sets of items 2 and 3 of Theorem A are marked non-colourable; each of
   the other 62 words w of period p satisfies w[n] != w[(n + d) mod p] for all n
   and all d in D, so n -> w[n mod p] is a proper k-colouring of G(D).
3. Exceptional sets (items 2 and 3, the "if" direction).  An exhaustive
   backtracking search (vertices coloured in increasing order, new colours
   introduced in increasing order) finds no proper k-colouring of {0,...,N-1}
   for (D, k, N) = ({1,2,3,5,8},5,13), ({1,4,5,6,7},5,17), ({1,2,3,4,5,7,12},7,19),
   and finds one on {0,...,N-2}, so these N are the shortest.
4. One-parameter families A5, A6, W2, W3 (Lemmas 3, 4, 5, Corollary 5').
   No element of W is divisible by k; r is not in W; every loop is E-proper
   for E = W u {r}, has length l + w (w = max E) and starts and ends with the
   state u; the numerical semigroup Lambda generated by the loop lengths has the
   stated largest gap g and contains g+1, ..., g+min(generators) (hence every
   integer > g); every x = k*s <= g + r is covered by x - r in Lambda (x - r >= 1)
   or x + r in Lambda, or else has a valid direct periodic colouring, and the
   direct list is exactly the set of uncovered x.  End-to-end check of Lemmas 4
   and 5: for every covered x <= g + r, and every x = k*s up to 3(g + r) (beyond
   the proof's needs, as a sanity check of Corollary 5'), the loop of length
   p = x -+ r is assembled by concatenating generator loops (Lemma 4(2)) and the
   resulting periodic colouring is checked directly on G(W u {x}).
5. Two-parameter family (Lemma 6).  The forms are F; each base vector (s0, t0)
   gives D(s0, t0) = B = {1,2,3,5,7,8}, and the six vectors of PROOF.md are among
   them; the loops for E = B, six colours, are valid; Lambda has largest gap 37
   and contains 38, ..., 43.  All coprime (s, t), t >= 1, with |s - 2t| <= 37,
   |s + 3t| <= 37 and six distinct nonzero values |as + bt| are enumerated (in a
   box much larger than the derived bound |t| <= 14, |s| <= 37); there must be
   334 of them, and each must have a base vector with N = |s t0 - t s0| >= 1 in
   Lambda.  End-to-end check of Lemma 6: for each of these 334 pairs, and for
   every valid pair with |s|, t <= 40 (sanity check), the colouring
   n -> c0(n (a s0 + b t0)), where a s + b t = 1, is built from concatenated loops
   and checked directly to be a proper 6-colouring of G(D(s, t)) of period N.
6. Lemma 2 on small cases.  For 2 <= k <= 8 and 1 <= s <= 4, the same exhaustive
   search finds no proper k-colouring of {0,...,ks} for D = {1,...,k-1,ks}.
"""

