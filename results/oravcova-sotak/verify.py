def group_exceptional(cert):
    listed = {}
    for rows in cert["sporadic"].values():
        for row in rows:
            if not row["colourable"]:
                listed[tuple(row["D"])] = row["interval"]
    report = []
    for D, (k, N) in EXCEPTIONAL.items():
        check(listed.get(D) == N, "%s: certificate interval %s, PROOF.md says %d" % (D, listed.get(D), N))
        found, nodes = exhaustive_colouring(D, k, N)
        check(found is None, "%s: a proper %d-colouring of {0..%d} exists" % (D, k, N - 1))
        shorter, _ = exhaustive_colouring(D, k, N - 1)
        check(shorter is not None and interval_colouring_ok(shorter, D, k),
              "%s: no proper %d-colouring of {0..%d}, so %d is not the shortest" % (D, k, N - 2, N))
        report.append("%s N=%d (%d nodes)" % ("{" + ",".join(map(str, D)) + "}", N, nodes))
    print("3. Exceptional sets: no proper colouring on " + ", ".join(report)
          + "; all three intervals one shorter are colourable")


