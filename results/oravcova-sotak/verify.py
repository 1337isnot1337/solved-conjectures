def group_tables(cert):
    counts = {"5": 12, "6": 9, "7": 27, "8": 17}
    n_sets = n_compared = 0
    notes = []
    for key, expected in counts.items():
        k = int(key)
        rows = cert["sporadic"][key]
        check(len(rows) == expected, "k=%d: %d listed sets, expected %d" % (k, len(rows), expected))
        for row in rows:
            D = row["D"]
            n_sets += 1
            check(len(D) == k and len(set(D)) == k, "%s does not have %d elements" % (D, k))
            check(D == sorted(D) and D[0] >= 1, "%s is not sorted positive" % D)
            check(reduce(gcd, D) == 1, "%s is not primitive" % D)
            L = loneliness(D)
            check(L == Fraction(row["L"]), "%s: L = %s, listed %s" % (D, L, row["L"]))
            check(L < Fraction(1, k), "%s: L = %s is not below 1/%d" % (D, L, k))
    for key, text in (("5", R5_TABLE), ("6", R6_TABLE)):
        mine = parse_grouped_table(text)
        theirs = set((tuple(r["D"]), r["L"]) for r in cert["sporadic"][key])
        check(mine == theirs, "k=%s table differs from the transcription of the repository: %s"
              % (key, sorted(mine ^ theirs)))
        n_compared += len(mine)
    for key, word in (("7", "seven"), ("8", "eight")):
        path = os.path.join(HERE, "..", "..", "results", "%s-speed-spectrum" % word, "sporadic.txt")
        if not os.path.exists(path):
            notes.append("%s not found, k=%s comparison skipped" % (os.path.normpath(path), key))
            continue
        repo = set()
        with open(path) as handle:
            for line in handle:
                parts = line.split()
                if parts:
                    repo.add((tuple(int(x) for x in parts[:-1]), parts[-1]))
        theirs = set((tuple(r["D"]), r["L"]) for r in cert["sporadic"][key])
        check(repo == theirs, "k=%s table differs from %s: %s" % (key, path, sorted(repo ^ theirs)))
        n_compared += len(repo)
    print("1. Tables: %d listed sets sorted, primitive, of size k, exact L recomputed and < 1/k; "
          "%d rows compared with the repository tables" % (n_sets, n_compared))
    for note in notes:
        print("   note: " + note)


