def group_one_parameter(cert):
    fams = {f["name"]: f for f in cert["one_parameter"]}
    check(sorted(fams) == sorted(FAMILY_TABLE), "families are %s" % sorted(fams))
    n_loops = n_x = n_direct = n_endtoend = 0
    for name, expected in FAMILY_TABLE.items():
        f = fams.get(name)
        if f is None:
            continue
        k, W, r = f["k"], f["W"], f["r"]
        check((k, W, r) == (expected["k"], expected["W"], expected["r"]),
              "%s: (k, W, r) = %s does not match PROOF.md" % (name, (k, W, r)))
        check(len(W) == k - 1, "%s: |W| != k - 1" % name)
        check(all(w % k != 0 for w in W), "%s: an element of W is divisible by k" % name)
        check(r not in W, "%s: r is in W" % name)
        E = sorted(W + [r])
        w = max(E)
        u = word_digits(f["state"], k)
        check(len(u) == w, "%s: state has length %d, expected %d" % (name, len(u), w))
        loops = {}
        for length_text, text in f["loops"].items():
            length = int(length_text)
            z = word_digits(text, k)
            check(is_loop(z, u, length, E), "%s: the loop of length %d is not valid" % (name, length))
            loops[length] = z
            n_loops += 1
        gens = sorted(loops)
        check(gens == expected["gens"], "%s: loop lengths %s, PROOF.md lists %s" % (name, gens, expected["gens"]))
        g = f["largest_gap"]
        check(g == expected["g"], "%s: largest gap %d, PROOF.md says %d" % (name, g, expected["g"]))
        top = 3 * (g + r) + 2 * max(gens) + 10
        S = semigroup_table(gens, top)
        check(not S[g], "%s: %d is in the semigroup" % (name, g))
        check(all(S[n] for n in range(g + 1, g + min(gens) + 1)),
              "%s: g+1..g+%d not all in the semigroup" % (name, min(gens)))
        uncovered = []
        for x in range(k, g + r + 1, k):
            n_x += 1
            check(x not in W, "%s: x = %d is in W" % (name, x))
            D = W + [x]
            if x - r >= 1 and S[x - r]:
                p = x - r
            elif S[x + r]:
                p = x + r
            else:
                uncovered.append(x)
                entry = f["direct"].get(str(x))
                if check(entry is not None, "%s: x = %d is not covered and has no direct colouring" % (name, x)):
                    word = word_digits(entry["word"], k)
                    check(len(word) == entry["period"], "%s: x = %d, word length != period" % (name, x))
                    check(is_periodic_proper(word, D), "%s: direct colouring for x = %d is not proper" % (name, x))
                    n_direct += 1
                continue
            z = concatenate_loops(loops, decomposition(gens, p))
            check(is_loop(z, u, p, E), "%s: assembled loop of length %d is not a loop" % (name, p))
            check(is_periodic_proper(z[:p], D), "%s: x = %d, period %d colouring is not proper" % (name, x, p))
            n_endtoend += 1
        check(uncovered == expected["direct"],
              "%s: uncovered x = %s, PROOF.md lists %s" % (name, uncovered, expected["direct"]))
        check(sorted(int(x) for x in f["direct"]) == uncovered,
              "%s: direct colourings given for %s, needed for %s" % (name, sorted(f["direct"]), uncovered))
        # sanity check of Corollary 5' beyond g + r (not needed by the proof)
        for x in range(k * ((g + r) // k + 1), 3 * (g + r) + 1, k):
            p = x - r
            z = concatenate_loops(loops, decomposition(gens, p))
            check(is_periodic_proper(z[:p], W + [x]), "%s: Corollary 5' colouring fails at x = %d" % (name, x))
            n_endtoend += 1
    print("4. One-parameter families: %d loops valid; semigroup gaps as stated; %d values x = ks <= g + r, "
          "%d needing direct colourings (all proper); %d assembled colourings checked end to end"
          % (n_loops, n_x, n_direct, n_endtoend))


