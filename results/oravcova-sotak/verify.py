# Group 5

def D_of(forms, s, t):
    return [abs(a * s + b * t) for a, b in forms]


def extended_gcd(a, b):
    if b == 0:
        return (a, 1, 0) if a >= 0 else (-a, -1, 0)
    g, x, y = extended_gcd(b, a % b)
    return g, y, x - (a // b) * y


def group_two_parameter(cert):
    tp = cert["two_parameter"]
    forms = [tuple(f) for f in tp["forms"]]
    check(forms == TWO_PARAM_FORMS, "forms are %s" % forms)
    base = tp["base"]
    B = base["B"]
    check(B == TWO_PARAM_B, "B = %s" % B)
    vectors = [tuple(v) for v in base["vectors"]]
    for v in vectors:
        check(sorted(D_of(forms, *v)) == B, "D%s = %s, not B" % (v, sorted(D_of(forms, *v))))
    check(all(v in vectors for v in TWO_PARAM_SIX_VECTORS), "a vector of PROOF.md is missing")
    k = 6
    u = word_digits(base["state"], k)
    check(u == [int(c) for c in "05123405"] and len(u) == max(B), "state is %s" % base["state"])
    loops = {}
    for length_text, text in base["loops"].items():
        z = word_digits(text, k)
        check(is_loop(z, u, int(length_text), B), "base loop of length %s is not valid" % length_text)
        loops[int(length_text)] = z
    gens = sorted(loops)
    check(gens == [6, 10, 29, 43], "loop lengths %s" % gens)
    g = base["largest_gap"]
    S = semigroup_table(gens, 2000)
    check(g == 37 and not S[37] and all(S[n] for n in range(38, 44)), "semigroup gap check failed")
    colourings = {}

    def colouring_for(s, t):
        """Return (N, word of period N) for G(D(s,t)) via Lemma 6, or None."""
        for s0, t0 in vectors:
            N = abs(s * t0 - t * s0)
            if N >= 1 and N < len(S) and S[N]:
                if N not in colourings:
                    colourings[N] = concatenate_loops(loops, decomposition(gens, N))[:N]
                c0 = colourings[N]
                _, a, b = extended_gcd(s, t)
                assert a * s + b * t == 1
                m = a * s0 + b * t0
                return N, [c0[(n * m) % N] for n in range(N)]
        return None

    def valid(s, t):
        values = D_of(forms, s, t)
        return gcd(abs(s), abs(t)) == 1 and 0 not in values and len(set(values)) == 6

    region = []
    for s in range(-300, 301):
        for t in range(1, 151):
            if valid(s, t) and abs(s - 2 * t) <= g and abs(s + 3 * t) <= g:
                region.append((s, t))
    check(all(abs(s) <= 37 and t <= 14 for s, t in region), "region exceeds |s| <= 37, t <= 14")
    check(len(region) == 334, "%d pairs in the finite region, PROOF.md says 334" % len(region))
    n_endtoend = 0
    for s, t in region:
        result = colouring_for(s, t)
        if check(result is not None, "(s,t) = (%d,%d) is not covered by a base vector" % (s, t)):
            N, word = result
            check(is_periodic_proper(word, D_of(forms, s, t)),
                  "(s,t) = (%d,%d): Lemma 6 colouring of period %d is not proper" % (s, t, N))
            n_endtoend += 1
    n_sanity = 0
    for s in range(-40, 41):
        for t in range(1, 41):
            if valid(s, t) and (s, t) not in region:
                result = colouring_for(s, t)
                if check(result is not None, "(s,t) = (%d,%d) outside the region not covered" % (s, t)):
                    N, word = result
                    check(is_periodic_proper(word, D_of(forms, s, t)),
                          "(s,t) = (%d,%d): Lemma 6 colouring is not proper" % (s, t))
                    n_sanity += 1
    print("5. Two-parameter family: %d base vectors give B; %d loops valid; largest gap %d; %d pairs in the "
          "finite region, all covered and checked end to end (plus %d pairs with |s|,t <= 40 outside it)"
          % (len(vectors), len(loops), g, len(region), n_sanity))


