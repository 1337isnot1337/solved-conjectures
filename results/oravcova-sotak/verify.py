# Group 2

def group_sporadic(cert):
    n_words = 0
    periods = []
    noncolourable = set()
    for key, rows in cert["sporadic"].items():
        k = int(key)
        for row in rows:
            D = row["D"]
            if not row["colourable"]:
                noncolourable.add(tuple(D))
                continue
            word = word_digits(row["word"], k)
            check(len(word) == row["period"], "%s: word length %d != period %d" % (D, len(word), row["period"]))
            check(is_periodic_proper(word, D), "%s: the periodic word is not a proper colouring" % D)
            periods.append(len(word))
            n_words += 1
    check(noncolourable == set(EXCEPTIONAL), "non-colourable listed sets are %s" % sorted(noncolourable))
    check(n_words == 62, "%d colourable listed sets, expected 62" % n_words)
    print("2. Sporadic colourings: %d periodic words are proper k-colourings (periods %d to %d); "
          "the %d sets marked non-colourable are exactly items 2 and 3"
          % (n_words, min(periods), max(periods), len(noncolourable)))


