# --------------------------------------------------------------------------
# Basic objects

def word_digits(text, k):
    digits = [int(ch) for ch in text]
    check(all(0 <= c < k for c in digits), "word %s uses a colour outside 0..%d" % (text, k - 1))
    return digits


def is_E_proper(z, E):
    """z_i != z_{i+d} whenever d in E and 0 <= i < i + d <= len(z) - 1 (Lemma 4)."""
    n = len(z)
    return all(z[i] != z[i + d] for d in E for i in range(n - d))


def is_periodic_proper(word, D):
    """n -> word[n mod p] is a proper colouring of G(D): word[n] != word[(n+d) mod p]."""
    p = len(word)
    return all(word[n] != word[(n + d) % p] for d in D for n in range(p))


def is_loop(z, u, length, E):
    """A loop of length l at u: an E-proper word of length l + w starting and ending with u."""
    w = len(u)
    return (length >= 1 and len(z) == length + w and z[:w] == u and z[length:] == u
            and is_E_proper(z, E))


def semigroup_table(gens, upto):
    S = [False] * (upto + 1)
    S[0] = True
    for n in range(1, upto + 1):
        S[n] = any(g <= n and S[n - g] for g in gens)
    return S


def decomposition(gens, n):
    """Write n >= 1 as a sum of generators (list), or None."""
    best = [None] * (n + 1)
    best[0] = []
    for m in range(1, n + 1):
        for g in gens:
            if g <= m and best[m - g] is not None:
                best[m] = best[m - g] + [g]
                break
    return best[n]


def concatenate_loops(loops, parts):
    """Lemma 4(2): z_0 ... z_{l-1} z' is a loop of length l + l'."""
    z = loops[parts[-1]]
    for length in reversed(parts[:-1]):
        z = loops[length][:length] + z
    return z


def norm_fraction(numerator, q):
    """|| numerator / q || as a Fraction."""
    r = numerator % q
    return Fraction(min(r, q - r), q)


def loneliness(D):
    best = Fraction(0)
    for i in range(len(D)):
        for j in range(i, len(D)):
            q = D[i] + D[j]
            for a in range(q + 1):
                value = min(norm_fraction(d * a, q) for d in D)
                if value > best:
                    best = value
    return best


def exhaustive_colouring(D, k, N):
    """Backtracking over {0,...,N-1}; returns (colouring or None, number of nodes)."""
    colour = [-1] * N
    nodes = 0
    stack = [(0, 0)]          # (position, next colour to try)
    maxused = [-1] * (N + 1)  # maxused[i] = largest colour among positions < i
    while stack:
        i, c = stack.pop()
        if i == N:
            return colour[:], nodes
        limit = min(maxused[i] + 1, k - 1)
        while c <= limit and any(i - d >= 0 and colour[i - d] == c for d in D):
            c += 1
        if c > limit:
            colour[i] = -1
            continue
        colour[i] = c
        nodes += 1
        maxused[i + 1] = max(maxused[i], c)
        stack.append((i, c + 1))
        stack.append((i + 1, 0))
    return None, nodes


def interval_colouring_ok(colouring, D, k):
    N = len(colouring)
    return (all(0 <= c < k for c in colouring)
            and all(colouring[i] != colouring[i + d] for d in D for i in range(N - d)))


