"""Propose exact rational interval certificates for the small distance graphs.

The generated Lean proofs verify the cover of all real times and the attaining
rational time. Haralambis's proved theorem then transfers equality to density.
This generator is not part of the trusted proof checker.
"""

from fractions import Fraction
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CASES = [
    (5, 1, 3, 7), (5, 2, 1, 3), (5, 3, 4, 11), (5, 4, 2, 5),
    (5, 5, 1, 3), (5, 7, 3, 8), (5, 12, 5, 13),
    (7, 1, 4, 9), (7, 2, 3, 10), (7, 3, 5, 13), (7, 4, 2, 5),
    (7, 5, 6, 17), (7, 6, 3, 7), (7, 7, 1, 3), (7, 9, 2, 5),
    (7, 11, 5, 12), (7, 12, 13, 31), (7, 14, 2, 5), (7, 16, 7, 17),
    (7, 18, 8, 19), (7, 23, 5, 12), (7, 25, 11, 26), (7, 32, 14, 33),
    (7, 50, 25, 58),
]


def rational(x):
    return str(x.numerator) if x.denominator == 1 else f"({x.numerator}/{x.denominator})"


def certificate(speeds, value):
    intervals = [
        (Fraction(k-value, d), Fraction(k+value, d), d, k)
        for d in speeds for k in range(d+1)
    ]
    chain = []
    right = Fraction(0)
    while right < 1:
        available = [c for c in intervals if c[0] <= right < c[1]]
        if not available:
            raise ValueError(f"Uncovered time {right} for {speeds}")
        chosen = max(available, key=lambda c: c[1])
        chain.append(chosen)
        right = chosen[1]
    candidates = (
        Fraction(a, x+y)
        for x, y in combinations(speeds, 2)
        for a in range((x+y)//2+1)
    )
    def clearance(t):
        return min(min((d*t)%1, 1-(d*t)%1) for d in speeds)
    t = next(t for t in candidates if clearance(t) == value)
    return chain, t, [(d*t).__floor__() for d in speeds]


def main():
    lines = [
        "import Conjectures.HaralambisTheorem", "",
        "/-! Exact small cases and the k=50 counterexample. Every covering",
        "interval and attaining time is checked by Lean over the rationals.",
        "Generated by distance-graph-densities/generate_three_distance_graph_examples.py. -/", "",
        "namespace ThreeDistanceGraph", "", "open Loneliness", "",
        "set_option maxRecDepth 100000", "set_option maxHeartbeats 4000000", "",
    ]
    for gap, k, numerator, denominator in CASES:
        speeds = [1, k, k+gap]
        value = Fraction(numerator, denominator)
        chain, t, shifts = certificate(speeds, value)
        name = f"gap{gap}_k{k}"
        rows = ",\n  ".join(f"⟨{rational(l)},{rational(r)},{d},{n}⟩" for l,r,d,n in chain)
        lines += [
            f"private def {name}Cover : List Segment := [", f"  {rows}]", "",
            f"theorem {name}_value : value {speeds} = ({rational(value)} : ℝ) := by",
            f"  have h := certified_value (ds:={speeds}) (r:={rational(value)})",
            f"    (cs:={name}Cover) (t:={rational(t)}) (ks:={shifts})",
            f"    (by norm_num [{name}Cover,Segment.Valid])",
            f"    (by norm_num [{name}Cover,coversFrom])",
            "    (by norm_num [LowerCertificate]) (by norm_num) (by norm_num)",
            "  norm_num at h", "  exact h", "",
            f"theorem {name}_density : Packing.density {speeds} = ({rational(value)} : ℝ) := by",
            f"  have h := Haralambis.density_eq_value (!{speeds} : Fin 3 → ℕ)",
            "    (by intro i; fin_cases i <;> norm_num)",
            f"  simpa [Haralambis.speeds,{name}_value] using h", "",
        ]
        print(f"{name}: {value}, time {t}, {len(chain)} intervals")
    lines += [
        "theorem counterexample_50_gap :",
        "    (22/51:ℝ)-Packing.density [1,50,57] = 1/2958 := by",
        "  rw [gap7_k50_density]", "  norm_num", "",
        "end ThreeDistanceGraph", "",
    ]
    path = ROOT / "lean/Conjectures/ThreeDistanceGraphSmall.lean"
    path.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
