#!/usr/bin/env python3
"""Generate the Lean fixture for the weighted residual intervals."""

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE.parents[1] / "lean" / "Conjectures" / "ShiftedLonelyRunnerWeightedData.lean"


def render(data):
    rows = ",\n".join(f"  ⟨{a}, {b}, {w}⟩" for a, b, w in data["support"])
    return """-- Generated by results/shifted-lonely-runner-counterexamples/generate_weighted_lean.py.
import Conjectures.ShiftedLonelyRunnerWeightedSeed

namespace ShiftedLonelyRunner.WeightedResidual

def support : List Cell := [
""" + rows + """
]

private theorem seed_checks :
    support.all (fun cell => row57.tracks.all (seedOK row57 cell)) = true := by
  decide +kernel

private theorem interval_checks :
    support.all (fun cell => decide (cell.left < cell.right ∧ cell.right ≤ period)) =
      true := by decide +kernel

theorem cell_valid {cell : Cell} (member : cell ∈ support) :
    cell.left < cell.right ∧ cell.right ≤ period := by
  simpa using List.all_eq_true.mp interval_checks cell member

theorem seed_misses {cell : Cell} (member : cell ∈ support)
    {track : Track} (old : track ∈ row57.tracks) {x : ℝ} (hx : x ∈ cell.times) :
    (1 : ℝ) / 59 < Loneliness.distance
      ((track.2 : ℝ) / row57.scale + track.1 * (x / period)) :=
  seedOK_sound (List.all_eq_true.mp (List.all_eq_true.mp seed_checks cell member) track old) hx

theorem support_weight :
    (support.map Cell.weight).sum = """ + str(data["total_weight"]) + """ := by decide +kernel

theorem support_mass :
    (support.map (fun c => c.weight * (c.right - c.left))).sum =
      """ + str(data["total_mass"]) + """ := by decide +kernel

end ShiftedLonelyRunner.WeightedResidual
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads((HERE / "weighted_residual.json").read_text(encoding="utf-8"))
    expected = render(data)
    if args.check:
        if TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Stale generated file {TARGET}")
    else:
        TARGET.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
