#!/usr/bin/env python3
"""Render bounded packed scalar blocks with an exact Lean equality certificate."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re


def render(source: str, prime: int, block_size: int) -> str:
    if prime < 3 or block_size < 1:
        raise ValueError("A modulus at least three and a positive block size are required")
    masks = [0] + [int(value, 16) for value in re.findall(r"mask := 0x([0-9a-fA-F]+)", source)]
    if len(masks) != prime // 2 + 1 or any(not 0 <= mask < 1 << prime for mask in masks):
        raise ValueError("The original scalar mask table has an unexpected shape")
    blocks = []
    for start in range(0, len(masks), block_size):
        packed = 0
        for offset, mask in enumerate(masks[start:start + block_size]):
            packed |= mask << (prime * offset)
        blocks.append(packed)

    def choose(lo: int, hi: int, indent: str) -> str:
        if hi - lo == 1:
            return indent + f"block{lo:03d}"
        middle = (lo + hi) // 2
        return (indent + f"if i < {middle} then\n" + choose(lo, middle, indent + "  ")
                + "\n" + indent + "else\n" + choose(middle, hi, indent + "  "))

    namespace = f"Loneliness.FiveSpeedCertificate.BlockPackedScalars.P{prime}B{block_size}"
    text = (
        "-- Generated by generate_lean_block_packed_scalar.py; finite equalities require the Lean kernel.\n"
        "import Conjectures.LonelinessFiveSpeedBlockPackedScalar\n"
        f"import Conjectures.LonelinessFiveSpeedPackedScalar{prime}\n\n"
        "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\nset_option Elab.async false\n\n"
        f"namespace {namespace}\n\n")
    for index, block in enumerate(blocks):
        text += f"noncomputable def block{index:03d} : ℕ := nat_lit 0x{block:x}\n\n"
    text += (
        "noncomputable def blocks (i : ℕ) : ℕ :=\n"
        f"  if i < {len(blocks)} then\n" + choose(0, len(blocks), "    ")
        + "\n  else\n    0\n\n"
        f"noncomputable def mask : ℕ → ℕ := blockPackedScalarMask {prime} {block_size} blocks\n\n"
        f"theorem checked : blockPackedScalarTreeCheck {prime} {block_size} blocks "
        f"ScalarTrees.P{prime}.tree = true := by\n  decide +kernel\n\n"
        f"theorem mask_eq_treeMask : mask = treeMask {prime} ScalarTrees.P{prime}.tree :=\n"
        f"  blockPackedScalarMask_eq_treeMask_function {prime} {block_size} blocks "
        f"ScalarTrees.P{prime}.tree checked\n\n"
        f"theorem mask_eq_packed : mask = PackedScalars.P{prime}.mask :=\n"
        f"  mask_eq_treeMask.trans PackedScalars.P{prime}.mask_eq_treeMask.symm\n\n"
        f"theorem sound (a : ℕ) : GoodMask {prime} a (mask a) :=\n"
        f"  blockPackedScalarTreeCheck_sound {prime} {block_size} blocks ScalarTrees.P{prime}.tree\n"
        f"    ScalarTrees.P{prime}.checked checked a\n\n"
        f"end {namespace}\n")
    return text


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prime", type=int, default=1789)
    parser.add_argument("--block-size", type=int, default=32)
    parser.add_argument("--lean-root", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = args.lean_root / "Conjectures" / f"LonelinessFiveSpeedScalarTreeMask{args.prime:04d}.lean"
    target = args.lean_root / "Conjectures" / (
        f"LonelinessFiveSpeedBlockPackedScalar{args.prime}B{args.block_size}.lean")
    raw = render(source.read_text(), args.prime, args.block_size).encode()
    if args.check:
        if not target.is_file() or target.read_bytes() != raw:
            raise ValueError("Published bounded packed source differs from deterministic renderer")
    else:
        if target.exists():
            raise ValueError("Use --check for an existing candidate source")
        target.write_bytes(raw)
    print(json.dumps({
        "status": "source bytes reproduced; Lean proof gates remain separate",
        "prime": args.prime, "block_size": args.block_size,
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "generated_sha256": hashlib.sha256(raw).hexdigest(), "generated_bytes": len(raw),
    }, sort_keys=True))


if __name__ == "__main__":
    main()
