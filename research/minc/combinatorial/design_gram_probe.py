def main():
    grams = []
    values = []
    for idx, block in enumerate(DATA.strip().split("\n\n"), 1):
        a = [[int(c) for c in line] for line in block.splitlines()]
        n = len(a)
        assert n == 15 and all(len(row) == n for row in a)
        assert all(sum(row) == 7 for row in a)
        assert all(sum(a[i][j] for i in range(n)) == 7 for j in range(n))
        gram = [[sum(x*y for x, y in zip(a[i], a[j])) for j in range(n)]
                for i in range(n)]
        assert all(gram[i][j] == (7 if i == j else 3)
                   for i in range(n) for j in range(n))
        grams.append(gram)
        p = permanent(a)
        values.append(p)
        print("design", idx, "permanent", p)
    assert all(g == grams[0] for g in grams)
    print("same Gram matrix:", True)
    print("same permanent:", len(set(values)) == 1)
    print("minimum among supplied designs:", min(values))


if __name__ == "__main__":
    main()
