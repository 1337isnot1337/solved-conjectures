"""Emit the Lean edge-cut certificate for all 6,842 partitions of 31.

This helper reuses the verified witness rows of ``li_partitions_final.py`` and
reorders them into the enumeration order of ``LiFinal.partsAux 31 31``, which is
the order consumed by ``lean/Conjectures/LiPartitionsFinalDataNN.lean``.

The partition enumeration is the same recursion as the Lean definition::

    partsAux 0 _       = [[]]
    partsAux (_+1) 0   = []
    partsAux (n+1) (k+1) =
        partsAux (n+1) k ++
          (if k < n+1 then map ((k+1) :: ·) (partsAux (n-k) (k+1)) else [])

so ``LiPartitionsFinalEnum.partsAux 31 31`` and the emitted partition columns
are definitionally the same list; the main module proves this equality with
``decide``.

Usage::

    python scripts/li_partitions_final_enum.py --write
    python scripts/li_partitions_final_enum.py --check
"""

import hashlib
import re
import sys
from functools import lru_cache
from pathlib import Path

import li_partitions_final as base

CHUNK = 500
ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "lean" / "Conjectures"
PREFIX = "LiPartitionsFinalData"


@lru_cache(None)
def parts_aux(n, k):
    """Partitions of ``n`` with parts at most ``k``, in decreasing order."""
    if n == 0:
        return ((),)
    if k == 0:
        return ()
    result = parts_aux(n, k - 1)
    if k <= n:
        result += tuple((k,) + rest for rest in parts_aux(n - k, k))
    return result


def ordered_rows():
    """The verified ``(partition, mask)`` rows in ``partsAux 31 31`` order."""
    _, rows = base.lean_rows()
    mask_of = {base.decode(parts): mask for parts, mask in rows}
    expected = parts_aux(31, 31)
    assert len(expected) == 6842, len(expected)
    assert len(set(expected)) == 6842
    assert set(expected) == set(mask_of), "enumeration is not the set of rows"
    ordered = [(kind, mask_of[kind]) for kind in expected]
    assert len({mask for _, mask in ordered}) == 6842
    # Recheck every row against the independent union-find implementation.
    for kind, mask in ordered:
        assert base.components(mask) == kind, (kind, mask)
    # The reference SHA-256 is over the reference row order; check it there.
    digest = hashlib.sha256(base.canonical(rows).encode()).hexdigest()
    print(f"rows: {len(ordered)}; reference-order sha256: {digest}")
    assert digest == base.REFERENCE_SHA256, digest
    return ordered


def lean_list(kind):
    return "[" + ", ".join(str(x) for x in kind) + "]"


def emit_chunk(index, chunk):
    file_name = f"{PREFIX}{index:02d}"
    name = f"data{index:02d}"
    lo = index * CHUNK
    hi = lo + len(chunk) - 1
    lines = [
        "import Conjectures.LiPartitionsFinalCore",
        "",
        "/-!",
        f"# Edge-cut certificate rows {lo}..{hi}",
        "",
        "Generated by `scripts/li_partitions_final_enum.py` from the verified",
        "witness rows of `scripts/li_partitions_final.py` (canonical SHA-256",
        "`30f51845828f4ec7b33a3762698b5a02148368d63a3503da3f496336f5f0fffd`).",
        "The partition column follows the enumeration order of",
        "`LiPartitionsFinalEnum.partsAux 31 31`.",
        "-/",
        "",
        "namespace LiFinal",
        "",
        "set_option maxHeartbeats 0",
        "set_option maxRecDepth 100000",
        "",
        f"/-- Certificate rows {lo}..{hi}. -/",
        f"def {name} : List Row := [",
    ]
    body = ",\n".join(
        f"  ({lean_list(kind)}, {mask})" for kind, mask in chunk
    )
    lines.append(body)
    lines.append("]")
    lines.append("")
    lines.append(f"theorem {name}_ok : chunkOk {name} = true := by")
    lines.append("  decide")
    lines.append("")
    lines.append("end LiFinal")
    lines.append("")
    return file_name, "\n".join(lines)


def write_all():
    rows = ordered_rows()
    names = []
    for start in range(0, len(rows), CHUNK):
        index = start // CHUNK
        name, text = emit_chunk(index, rows[start:start + CHUNK])
        path = OUT_DIR / f"{name}.lean"
        path.write_text(text, encoding="utf-8", newline="\n")
        names.append(name)
        print(f"wrote {path.relative_to(ROOT)} ({len(rows[start:start + CHUNK])} rows)")
    return names


ROW_RE = re.compile(r"^\s*\(\[([0-9,\s]*)\],\s*([0-9]+)\)\s*,?\s*$")


def check_files():
    expected = parts_aux(31, 31)
    position = 0
    for path in sorted(OUT_DIR.glob(f"{PREFIX}*.lean")):
        for line in path.read_text(encoding="utf-8").splitlines():
            match = ROW_RE.match(line)
            if not match:
                continue
            kind = tuple(int(x) for x in match.group(1).split(","))
            mask = int(match.group(2))
            assert position < len(expected), "too many rows"
            assert kind == expected[position], (path, position, kind, expected[position])
            assert base.components(mask) == kind, (path, kind, mask)
            position += 1
        print(f"checked {path.name}")
    assert position == len(expected), (position, len(expected))
    print(f"all {position} rows checked, in partsAux order")


def main():
    if "--write" in sys.argv:
        names = write_all()
        print(f"chunks: {len(names)}")
    elif "--check" in sys.argv:
        check_files()
    else:
        rows = ordered_rows()
        print(f"would write {(len(rows) + CHUNK - 1) // CHUNK} chunks")


if __name__ == "__main__":
    main()
