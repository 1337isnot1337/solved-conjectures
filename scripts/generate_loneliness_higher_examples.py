#!/usr/bin/env python3
"""Generate exact real-time certificates for the higher-speed example tables.

This script is an untrusted certificate producer. The generated Lean proofs
check the rational interval covering and the attaining rational time. They do
not claim that the listed tuples exhaust any spectrum or equality case.
"""

from fractions import Fraction
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rational(value):
    value = Fraction(value)
    if value.denominator == 1:
        return str(value.numerator)
    return f"({value.numerator} / {value.denominator})"


def table(slug, count, arity):
    rows = []
    for row in (ROOT / "results" / slug / "sporadic.txt").read_text().splitlines():
        if not row.strip():
            continue
        fields = row.split()
        speeds, value = list(map(int, fields[:-1])), Fraction(fields[-1])
        assert len(speeds) == arity and speeds == sorted(set(speeds))
        assert speeds[0] > 0 and 0 < value <= Fraction(1, 2)
        rows.append((speeds, value))
    assert len(rows) == count
    return rows


def minimum_distance(speeds, time):
    phases = [(d * time) % 1 for d in speeds]
    return min(min(phase, 1 - phase) for phase in phases)


def certificate(speeds, value):
    intervals = [
        ((k - value) / d, (k + value) / d, d, k)
        for d in speeds
        for k in range(d + 1)
    ]
    chain, right = [], Fraction(0)
    while right < 1:
        available = [c for c in intervals if c[0] <= right < c[1]]
        if not available:
            raise ValueError(f"Uncovered time {right} for {speeds} at bound {value}")
        chosen = max(available, key=lambda c: c[1])
        chain.append(chosen)
        right = chosen[1]
    candidates = (
        Fraction(k, a + b)
        for a, b in combinations(speeds, 2)
        for k in range((a + b) // 2 + 1)
    )
    time = next(t for t in candidates if minimum_distance(speeds, t) == value)
    shifts = [(d * time).__floor__() for d in speeds]
    return chain, time, shifts


def write_module(suffix, label, rows):
    lines = [
        "import Conjectures.LonelinessHigherExamplesCertificate",
        "",
        f"/-! Exact maxima for {label}.",
        "Every interval bound and attaining time is checked in Lean.",
        "These theorems do not assert exhaustiveness of the example list.",
        "Generated by scripts/generate_loneliness_higher_examples.py. -/",
        "",
        "namespace Loneliness.HigherExamples",
        "",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 4000000",
        "",
    ]
    for index, (speeds, value) in enumerate(rows, 1):
        name = f"{suffix.lower()}_{index:02d}"
        chain, time, shifts = certificate(speeds, value)
        data = ",\n  ".join(
            f"⟨{rational(left)}, {rational(right)}, {d}, {k}⟩"
            for left, right, d, k in chain
        )
        r, t = rational(value), rational(time)
        lines += [
            f"def {name}Cover : List Segment := [",
            f"  {data}]",
            "",
            f"theorem {name}_value : value {speeds} = ({r} : ℝ) := by",
            f"  have h := certified_value (ds := {speeds}) (r := {r})",
            f"    (cs := {name}Cover) (t := {t}) (ks := {shifts})",
            f"    (by norm_num [{name}Cover, Segment.Valid])",
            f"    (by norm_num [{name}Cover, coversFrom])",
            "    (by norm_num [LowerCertificate]) (by norm_num) (by norm_num)",
            "  norm_num at h",
            "  exact h",
            "",
            f"theorem {name}_maximum : clearance {speeds} ({t} : ℝ) = ({r} : ℝ) ∧",
            f"    ∀ u : ℝ, clearance {speeds} u ≤ ({r} : ℝ) := by",
            f"  have hv : value {speeds} = (({r} : ℚ) : ℝ) := by",
            f"    norm_num; exact {name}_value",
            f"  have h := maximum_of_value_certificate (ds := {speeds})",
            f"    (r := {r}) (t := {t}) (ks := {shifts}) hv",
            "    (by norm_num [LowerCertificate]) (by norm_num)",
            "  norm_num at h",
            "  exact h",
            "",
        ]
        print(f"{name}: value={value}, time={time}, intervals={len(chain)}")
    lines += ["end Loneliness.HigherExamples", ""]
    out = ROOT / f"lean/Conjectures/LonelinessHigherExamples{suffix}.lean"
    out.write_text("\n".join(lines))


def main():
    write_module("Seven", "all 27 listed seven-speed sporadic tuples",
                 table("seven-speed-spectrum", 27, 7))
    write_module("Eight", "all 17 listed eight-speed sporadic tuples",
                 table("eight-speed-spectrum", 17, 8))
    write_module("Equality", "the exceptional thirteen-speed equality tuple",
                 [(list(range(1, 12)) + [13, 24], Fraction(1, 14))])


if __name__ == "__main__":
    main()
