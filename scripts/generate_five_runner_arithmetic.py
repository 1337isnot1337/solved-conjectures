#!/usr/bin/env python3
"""Render arithmetic inputs for the finite five-runner prime certificates.

The JSON producer and this renderer are untrusted.  Every numerical assertion
emitted here is proved by ordinary Lean kernel reduction.  No assertion about
coverage of the support search is emitted by this renderer.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from math import isqrt
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def rarray(values: list[str], lo: int = 0, hi: int | None = None, indent: int = 2) -> str:
    """A balanced RArray indexed by the original absolute position."""
    if hi is None:
        hi = len(values)
    if hi <= lo:
        raise ValueError("RArray requires a nonempty list")
    pad = " " * indent
    if hi - lo == 1:
        return pad + "(.leaf " + values[lo] + ")"
    mid = (lo + hi) // 2
    return (pad + f"(.branch {mid}\n" + rarray(values, lo, mid, indent + 2) + "\n"
            + rarray(values, mid, hi, indent + 2) + "\n" + pad + ")")


def memo(entries: list[tuple[int, int]], indent: int = 2) -> str:
    """A balanced memo tree; all returned entries are separately checked."""
    pad = " " * indent
    if not entries:
        return pad + ".empty"
    if len(entries) == 1:
        key, value = entries[0]
        return pad + f"(.entry {key} {value})"
    mid = len(entries) // 2
    return (pad + f"(.branch {entries[mid][0]}\n" + memo(entries[:mid], indent + 2)
            + "\n" + memo(entries[mid:], indent + 2) + "\n" + pad + ")")


def namespace(p: int) -> str:
    return f"Loneliness.Modular.FiveRunner.Prime{p:04}"


def module(p: int, suffix: str) -> str:
    return f"Conjectures.LonelinessFiveRunnerPrime{p:04}{suffix}"



def validate(data: dict) -> None:
    """Check every literal arithmetic input independently before rendering."""
    p = data["p"]
    half = p // 2
    if data["schema"] != "five-runner-prime-support-v1":
        raise ValueError("Unexpected input schema")
    if p <= 135 or any(p % a == 0 for a in range(2, isqrt(p) + 1)):
        raise ValueError("Expected a prime larger than 135")
    if data["half"] != half or data["width"] != half + 1:
        raise ValueError("Incorrect folded interval")
    inverse = data["inverse"]
    if len(inverse) != half + 1 or inverse[0] != 0:
        raise ValueError("Incorrect inverse table shape")
    for a in range(1, half + 1):
        if a * inverse[a] % p != 1:
            raise ValueError(f"Incorrect inverse at {a}")
    fold = lambda a: min(a % p, (-a) % p)
    covers = [int(value) for value in data["cover"]]
    if len(covers) != half + 1:
        raise ValueError("Incorrect cover table shape")
    for a, value in enumerate(covers):
        expected = sum(1 << t for t in range(1, half + 1) if 6 * fold(t * a) < p)
        if value != expected:
            raise ValueError(f"Incorrect cover mask at {a}")
    directions = [[1, 2, 3, 4, 5], [1, 3, 4, 5, 9]]
    expected_rows = [{"root": sorted(fold(inverse[t] * j) for j in direction),
                      "time": t, "direction": direction}
                     for direction in directions for t in direction]
    if data["rows"] != expected_rows:
        raise ValueError("Incorrect ten retained rows")
    seen = set()
    for root in data["roots"]:
        b = root["b"]
        if b in seen or not 2 <= b <= half:
            raise ValueError("Repeated or out-of-range minimum pair")
        seen.add(b)
        compatible = lambda a, c: (0 < a <= half and 0 < c <= half
            and b <= fold(inverse[a] * c) and b <= fold(inverse[c] * a))
        for key, value in root["compatible"].items():
            a = int(key)
            expected = sum(1 << c for c in range(1, half + 1) if compatible(a, c))
            if int(value) != expected:
                raise ValueError(f"Incorrect compatibility mask at b={b}, a={a}")
        expected = {
            "selected": (1 << 1) | (1 << b),
            "available": sum(1 << a for a in range(b + 1, half + 1)
                             if compatible(1, a) and compatible(b, a)),
            "uncovered": ((1 << (half + 1)) - 2) & ~(covers[1] | covers[b]),
            "slots": 3,
        }
        for key, value in expected.items():
            if int(root["initial"][key]) != value:
                raise ValueError(f"Incorrect initial {key} at b={b}")


def shared_arithmetic(data: dict) -> str:
    p, half = data["p"], data["half"]
    width = half + 1
    ns = namespace(p)
    return f"""import Conjectures.LonelinessModularInitialMemo
import Init.Data.RArray

/-! Arithmetic tables for the prime-{p} five-runner support certificates.
Generated by scripts/generate_five_runner_arithmetic.py.
Every cached value is checked against the original finite-set definition. -/

namespace {ns}

set_option maxRecDepth 16384
set_option maxHeartbeats 0

def inverseData : Lean.RArray ℕ :=
{rarray([str(a) for a in data['inverse']])}

def inverse (a : ℕ) : ℕ := if a < {width} then inverseData.get a else 0

theorem inverse_checked : ∀ a : Fin {width}, 0 < a.val →
    (a.val * inverse a.val) % {p} = 1 := by
  decide +kernel

theorem inverse_valid (a : ℕ) (ha : 0 < a) (hbound : 2 * a ≤ {p}) :
    (a * inverse a) % {p} = 1 % {p} := by
  have hlt : a < {width} := by omega
  exact inverse_checked ⟨a, hlt⟩ ha

def coverTable : Memo.Tree :=
{memo([(a, int(value)) for a, value in enumerate(data['cover'])])}

def coverMask : ℕ → ℕ := InitialMemo.cover 6 {p} coverTable

theorem cover_checked : Memo.check (InitialBits.cover 6 {p}) coverTable = true := by
  decide +kernel

end {ns}
"""



def retained_rows(data: dict) -> str:
    p = data["p"]
    ns = namespace(p)
    entries = ["⟨![" + ", ".join(map(str, row["root"])) + "], " + str(row["time"])
               + ", [" + ", ".join(map(str, row["direction"])) + "]⟩"
               for row in data["rows"]]
    lines = [
        "import Conjectures.LonelinessFiveRunnerFinite",
        "import Mathlib.Data.Fin.VecNotation",
        "import Mathlib.Tactic.FinCases", "",
        f"/-! Ten retained rows for prime {p}. Row.Valid checks injectivity,",
        "the radius-nine bound, and one of the two primitive target directions. -/", "",
        f"namespace {ns}", "",
        "def rows : Fin 10 → Row :=", "  ![" + ",\n    ".join(entries) + "]", "",
    ]
    for i in range(10):
        lines += [f"theorem row{i}_valid : (rows {i}).Valid {p} := by", "  decide +kernel", ""]
    lines += [f"theorem rows_valid (i : Fin 10) : (rows i).Valid {p} := by", "  fin_cases i"]
    lines += [f"  · exact row{i}_valid" for i in range(10)]
    lines += ["", "def terminal : Finset ℕ → ℕ → Bool := FiveRunner.terminal rows", "",
        "theorem terminal_sound :",
        "    ∀ s index, terminal s index = true → Retained rows s :=",
        "  FiveRunner.terminal_sound rows", "", f"end {ns}", ""]
    return "\n".join(lines)


def root_arithmetic(data: dict, root: dict) -> str:
    p, b = data["p"], root["b"]
    width = data["half"] + 1
    ns = namespace(p) + f".B{b:03}"
    entries = sorted((b * width + int(a), int(value)) for a, value in root["compatible"].items())
    initial = {key: int(root["initial"][key]) for key in ("selected", "available", "uncovered")}
    return f"""import {module(p, 'Arithmetic')}

/-! Exact arithmetic for minimum pair {b} at prime {p}.
Generated by scripts/generate_five_runner_arithmetic.py. -/

namespace {ns}

set_option maxRecDepth 16384
set_option maxHeartbeats 0

def compatibleTable : Memo.Tree :=
{memo(entries)}

def compatibleMask : ℕ → ℕ :=
  InitialMemo.compatible {p} inverse {width} compatibleTable {b}

theorem compatible_checked :
    Memo.check (InitialMemo.compatibleBase {p} inverse {width}) compatibleTable = true := by
  decide +kernel

theorem selected_mask_checked :
    InitialBits.encode (InitialSupport.selected {b}) = {initial['selected']} := by
  decide +kernel

theorem available_mask_checked :
    InitialBits.encode (InitialSupport.available {p} inverse {b}) = {initial['available']} := by
  decide +kernel

theorem uncovered_mask_checked :
    InitialBits.encode (InitialSupport.uncovered 6 {p} {b}) = {initial['uncovered']} := by
  decide +kernel

end {ns}
"""


def rendered(data: dict) -> dict[str, str]:
    p = data["p"]
    result = {module(p, "Arithmetic"): shared_arithmetic(data),
              module(p, "Rows"): retained_rows(data)}
    result.update({module(p, f"B{root['b']:03}Arithmetic"): root_arithmetic(data, root)
                   for root in data["roots"]})
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("json", type=Path)
    parser.add_argument("--repo", type=Path, default=ROOT)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads(args.json.read_text())
    validate(data)
    summary = []
    for name, text in rendered(data).items():
        path = args.repo / "lean" / (name.replace(".", "/") + ".lean")
        content = text.encode()
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        elif path.read_bytes() != content:
            raise RuntimeError("Generated source differs: " + str(path))
        summary.append({"module": name, "bytes": len(content),
                        "sha256": hashlib.sha256(content).hexdigest()})
    print(json.dumps({"schema": "five-runner-prime-arithmetic-v1", "prime": data["p"],
                      "minimum_pairs": [root["b"] for root in data["roots"]],
                      "files": summary}, indent=2))


if __name__ == "__main__":
    main()
