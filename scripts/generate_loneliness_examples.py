#!/usr/bin/env python3
"""Produce exact-value Lean certificates for the explicit speed sets in the notes.

This script is untrusted. Lean independently reduces every finite certificate,
and the checked pair-sum theorem supplies the upper bound for all real times.
No classification of all speed sets follows from these individual values.
"""

