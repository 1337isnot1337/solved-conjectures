def witness(speeds):
    best = Fraction(-1)
    time = Fraction(0)
    for a, b in combinations(speeds, 2):
        q = a + b
        for k in range(q // 2 + 1):
            val = min(Fraction(min(d * k % q, q - d * k % q), q) for d in speeds)
            if val > best:
                best, time = val, Fraction(k, q)
    return best, time


def main():
    lines = [
        "import Conjectures.LonelinessCertificate",
        "",
        "/-! Exact global values for the explicit sets in the repository.",
        "Generated by scripts/generate_loneliness_examples.py; Lean checks the",
        "certificates independently. These are not exhaustiveness claims. -/",
        "namespace Loneliness.PairSum.Examples",
        "",
        "set_option maxRecDepth 20000",
        "set_option maxHeartbeats 0",
        "",
    ]
    for name, speeds, numerator, denominator in CASES:
        value, time = witness(speeds)
        assert value == Fraction(numerator, denominator), (name, value)
        ds = "[" + ",".join(map(str, speeds)) + "]"
        lines.extend([
            f"theorem {name} : IsExactValue {ds} (({numerator} : ℝ)/{denominator}) := by",
            f"  simpa only [Nat.cast_one, Nat.cast_ofNat] using certified_exact_value {ds} (by decide) (by decide) (by decide)",
            f"    {numerator} {denominator} {time.numerator} {time.denominator}",
            "    (by decide) (by decide) (by decide) (by decide)",
            "",
        ])
    lines.append("end Loneliness.PairSum.Examples")
    root = Path(__file__).resolve().parents[1]
    out = root / "lean/Conjectures/LonelinessExamples.lean"
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(CASES)} exact-value certificates to {out.relative_to(root)}")


if __name__ == "__main__":
    main()
