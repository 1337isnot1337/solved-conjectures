def existing_twelve_rows():
    """Read the checked-in table without rerunning the floating-point LP."""
    folder = ROOT / "lean/Conjectures"
    stem = "LonelinessKZProductDataTwelve"
    base = folder / f"{stem}Base.lean"
    if base.exists():
        header = base.read_text()
        files = [folder / f"{stem}Block{b:02d}.lean" for b in range(8)]
        sizes = [256] * 8
    else:
        files = [folder / f"{stem}.lean"]
        header = files[0].read_text()
        sizes = [2048]
    scale = int(re.search(r"def boundScale : ℕ := (\d+)", header).group(1))
    scaled = [int(x) for x in re.search(r"def boundData : Array ℕ := #\[([^]]*)\]", header).group(1).split(",")]

    def pivots(lo, hi):
        if hi-lo == 1:
            return []
        middle = (lo+hi)//2
        return [middle] + pivots(lo, middle) + pivots(middle, hi)

    rows = []
    for path, size in zip(files, sizes):
        text = path.read_text()
        found = re.findall(r"\(\.leaf ⟨(?:⟨)?(\d+), #\[([0-9, ]*)\]", text)
        assert len(found) == size, (path, len(found))
        assert [int(x) for x in re.findall(r"\(\.branch (\d+)", text)] == pivots(0, size)
        rows += [(int(q), [int(x) for x in weights.split(",")]) for q, weights in found]
    assert len(rows) == 2048 and len(scaled) == 12
    d = 11
    for mask, (q, weights) in enumerate(rows):
        assert q > 0 and len(weights) == 2*d and all(w >= 0 for w in weights)
        for i in range(d):
            lhs = sum(weights[i:d]) + (4*weights[d+i-1] if i else 0)
            rhs = (q if (mask >> i)&1 else 0) + (3*weights[d+i] if i+1 < d else 0)
            assert lhs == rhs, (mask, i, "coefficient mismatch")
        assert q*scaled[mask.bit_count()] <= sum(weights[r]*scaled[r+1] for r in range(d))
    return scale, scaled, rows


def repackage_existing_twelve():
    """Preserve every denominator, weight and mask while splitting the checks."""
    before = existing_twelve_rows()
    write_partitioned_twelve(*before)
    after = existing_twelve_rows()
    assert after == before, "Partitioning changed an existing numerical certificate"
    public = (ROOT / "lean/Conjectures/LonelinessKZProductDataTwelve.lean").read_text()
    assert "theorem rows_valid (m : Fin (2^11)) :\n    DualValid 11 bounds (fun i => m.val.testBit i.val) (row m) := by" in public
    payload = json.dumps(before, separators=(",", ":")).encode()
    print("12 speeds: preserved all 2048 rows; eight 256-row FastValid modules; "
          f"numeric SHA256 {hashlib.sha256(payload).hexdigest()}", flush=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("speeds", nargs="*", type=int, choices=range(9, 14))
    parser.add_argument("--repackage-existing", action="store_true",
                        help="repackage existing 12-speed rows without rerunning the LP")
    args = parser.parse_args()
    if args.repackage_existing:
        if args.speeds != [12]:
            parser.error("--repackage-existing requires exactly the speed count 12")
        repackage_existing_twelve()
        return
    for k in args.speeds or range(9, 14):
        produce(k)


if __name__ == "__main__":
    main()
