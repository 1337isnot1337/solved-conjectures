#!/usr/bin/env python3
"""Produce exact dual certificates for every KZ subset inequality.

SciPy proposes nonnegative LP duals. Fraction arithmetic then checks every
coefficient and bound exactly. The generated Lean file independently checks
the resulting integer certificate, including every subset of the dimension.
"""

from fractions import Fraction
from math import lcm
from pathlib import Path
import argparse

import numpy as np
from scipy.optimize import linprog

ROOT = Path(__file__).resolve().parents[1]


def bounds(k):
    return [4 * (Fraction(1, k + 1 - r) - Fraction(1, k + 1))**2
            for r in range(k)]


def produce(k):
    d = k - 1
    prefix = bounds(k)
    scale = lcm(*(b.denominator for b in prefix))
    scaled = [int(scale * b) for b in prefix]
    matrix = [[int(i <= r) for i in range(d)] for r in range(d)]
    matrix += [[-3 if i == r else 4 if i == r + 1 else 0 for i in range(d)]
               for r in range(d - 1)]
    constants = prefix[1:] + [Fraction(0)] * (d - 1)
    af = -np.array(matrix, dtype=float)
    bf = -np.array(constants, dtype=float)
    rows = [(1, [0] * (2*d))]
    for mask in range(1, 2**d):
        target = [(mask >> i) & 1 for i in range(d)]
        result = linprog(target, A_ub=af, b_ub=bf, bounds=[(None, None)]*d,
                         method="highs", options={"dual_feasibility_tolerance": 1e-9,
                                                  "primal_feasibility_tolerance": 1e-9})
        if not result.success:
            raise ValueError((k, mask, result.message))
        dual = [Fraction(float(-x)).limit_denominator(100_000_000)
                for x in result.ineqlin.marginals]
        assert all(x >= 0 for x in dual), (k, mask, "negative coefficient")
        assert [sum(dual[r] * matrix[r][i] for r in range(2*d-1))
                for i in range(d)] == target, (k, mask, "coefficient mismatch")
        assert sum(dual[r] * constants[r] for r in range(2*d-1)) >= prefix[mask.bit_count()], \
            (k, mask, "insufficient lower bound")
        q = lcm(*(x.denominator for x in dual))
        weights = [int(q * x) for x in dual] + [0]
        assert q * scaled[mask.bit_count()] <= sum(weights[r] * scaled[r+1] for r in range(d))
        rows.append((q, weights))
    name = f"Nine" if k == 9 else {10: "Ten", 11: "Eleven", 12: "Twelve", 13: "Thirteen"}[k]
    lines = [
        ("import Conjectures.LonelinessKZProductFast" if d >= 12 else
         "import Conjectures.LonelinessKZProductCertificate") + ("\nimport Init.Data.RArray" if d > 8 else ""),
        "",
        f"/-! Integer LP-dual certificates for dimension {d}.",
        f"All {2**d} subsets are checked; no values of the real variables are sampled.",
        "Generated by scripts/generate_loneliness_kz_certificates.py. -/",
        "",
        f"namespace Loneliness.KZProduct.{name}",
        "",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0",
        "",
        f"def boundScale : ℕ := {scale}",
        f"def boundData : Array ℕ := #[{', '.join(map(str, scaled))}]",
        "def bounds (r : ℕ) : ℕ := boundData[r]?.getD 0",
        "",
    ]
    lines += data_lines(rows, d)
    lines += verification(d)
    lines += ["", f"end Loneliness.KZProduct.{name}", ""]
    output = ROOT / f"lean/Conjectures/LonelinessKZProductData{name}.lean"
    output.write_text("\n".join(lines))
    print(f"{k} speeds: {len(rows)} exact certificates, bound scale {scale}, {output.name}", flush=True)


def data_lines(rows, d):
    if d <= 8:
        return ["def rowData : Array DualRow := #["] + [
            f"  ⟨{q}, #[{', '.join(map(str, weights))}]⟩" + ("," if i+1<len(rows) else "]")
            for i, (q, weights) in enumerate(rows)]
    def tree(lo, hi, indent):
        pad = " " * indent
        if hi-lo == 1:
            q, weights = rows[lo]
            dual = f"⟨{q}, #[{', '.join(map(str, weights))}]⟩"
            if d >= 12:
                tails = [sum(weights[i:d]) for i in range(d+1)]
                for i in range(d):
                    assert tails[i] + (4*weights[d+i-1] if i else 0) == \
                        (q if (lo >> i)&1 else 0) + (3*weights[d+i] if i+1 < d else 0)
                dual = f"⟨{dual}, #[{', '.join(map(str, tails))}]⟩"
            return [pad + f"(.leaf {dual})"]
        mid = (lo+hi)//2
        return ([pad+f"(.branch {mid}"] + tree(lo, mid, indent+2) +
                tree(mid, hi, indent+2) + [pad+")"])
    row_type = "FastRow" if d >= 12 else "DualRow"
    definition = "noncomputable def" if d >= 12 else "def"
    return [f"{definition} rowData : Lean.RArray {row_type} :="] + tree(0, len(rows), 2)


def verification(d):
    row_def = (f"def row (m : Fin (2^{d})) : DualRow := rowData[m.val]?.getD default" if d <= 8 else
               f"noncomputable def row (m : Fin (2^{d})) : DualRow := rowData.get m.val")
    lines = ["", row_def, ""]
    if d >= 12:
        lines = ["", f"noncomputable def certificate (m : Fin (2^{d})) : FastRow := rowData.get m.val",
                 f"noncomputable def row (m : Fin (2^{d})) : DualRow := (certificate m).dual", ""]
    if d <= 8:
        return lines + [f"theorem rows_valid : ∀ m : Fin (2^{d}),",
                        f"    DualValid {d} bounds (fun i => m.val.testBit i.val) (row m) := by decide +kernel"]
    block_size = 64
    blocks = 2**d // block_size
    predicate = "FastValid" if d >= 12 else "DualValid"
    accessor = "certificate" if d >= 12 else "row"
    for block in range(blocks):
        lines += [f"private theorem rows_valid_block_{block} : ∀ j : Fin {block_size},",
                  f"    {predicate} {d} bounds (fun i => ({block}*{block_size}+j.val).testBit i.val)",
                  f"      ({accessor} ⟨{block}*{block_size}+j.val, by omega⟩) := by decide +kernel", ""]
    lines += [f"theorem rows_valid (m : Fin (2^{d})) :",
              f"    DualValid {d} bounds (fun i => m.val.testBit i.val) (row m) := by"]
    if d >= 12:
        lines += ["  apply fast_valid_correct bounds (fun i => m.val.testBit i.val) (certificate m)"]
    lines += [f"  let q := m.val / {block_size}",
              f"  let j : Fin {block_size} := ⟨m.val % {block_size}, Nat.mod_lt _ (by decide)⟩",
              f"  have hq : q < {blocks} := by dsimp [q]; omega",
              f"  have he : m.val = q*{block_size}+j.val := by dsimp [q,j]; omega",
              "  interval_cases q"]
    for block in range(blocks):
        lines += [f"  · have hm : m = ⟨{block}*{block_size}+j.val, by omega⟩ := Fin.ext he",
                  "    rw [hm]", f"    exact rows_valid_block_{block} j"]
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("speeds", nargs="*", type=int, choices=range(9, 14))
    args = parser.parse_args()
    for k in args.speeds or range(9, 14):
        produce(k)


if __name__ == "__main__":
    main()
