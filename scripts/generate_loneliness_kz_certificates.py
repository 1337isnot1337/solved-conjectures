#!/usr/bin/env python3
"""Produce exact dual certificates for every KZ subset inequality.

SciPy proposes nonnegative LP duals. Fraction arithmetic then checks every
coefficient and bound exactly. The generated Lean file independently checks
the resulting integer certificate, including every subset of the dimension.
"""

from fractions import Fraction
from math import lcm
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def bounds(k):
    return [4 * (Fraction(1, k + 1 - r) - Fraction(1, k + 1))**2
            for r in range(k)]


def produce(k):
    import numpy as np
    from scipy.optimize import linprog

    d = k - 1
    prefix = bounds(k)
    scale = lcm(*(b.denominator for b in prefix))
    scaled = [int(scale * b) for b in prefix]
    matrix = [[int(i <= r) for i in range(d)] for r in range(d)]
    matrix += [[-3 if i == r else 4 if i == r + 1 else 0 for i in range(d)]
               for r in range(d - 1)]
    constants = prefix[1:] + [Fraction(0)] * (d - 1)
    af = -np.array(matrix, dtype=float)
    bf = -np.array(constants, dtype=float)
    rows = [(1, [0] * (2*d))]
    for mask in range(1, 2**d):
        target = [(mask >> i) & 1 for i in range(d)]
        result = linprog(target, A_ub=af, b_ub=bf, bounds=[(None, None)]*d,
                         method="highs", options={"dual_feasibility_tolerance": 1e-9,
                                                  "primal_feasibility_tolerance": 1e-9})
        if not result.success:
            raise ValueError((k, mask, result.message))
        dual = [Fraction(float(-x)).limit_denominator(100_000_000)
                for x in result.ineqlin.marginals]
        assert all(x >= 0 for x in dual), (k, mask, "negative coefficient")
        assert [sum(dual[r] * matrix[r][i] for r in range(2*d-1))
                for i in range(d)] == target, (k, mask, "coefficient mismatch")
        assert sum(dual[r] * constants[r] for r in range(2*d-1)) >= prefix[mask.bit_count()], \
            (k, mask, "insufficient lower bound")
        q = lcm(*(x.denominator for x in dual))
        weights = [int(q * x) for x in dual] + [0]
        assert q * scaled[mask.bit_count()] <= sum(weights[r] * scaled[r+1] for r in range(d))
        rows.append((q, weights))
    name = f"Nine" if k == 9 else {10: "Ten", 11: "Eleven", 12: "Twelve", 13: "Thirteen"}[k]
    if k == 12:
        write_partitioned_twelve(scale, scaled, rows)
        print(f"{k} speeds: {len(rows)} exact certificates, bound scale {scale}, "
              "eight 256-row modules plus bounds and dispatch", flush=True)
        return
    if k == 13:
        write_partitioned_thirteen(scale, scaled, rows)
        print(f"{k} speeds: {len(rows)} exact certificates, bound scale {scale}, "
              "sixteen 256-row modules plus bounds and dispatch", flush=True)
        return
    lines = [
        ("import Conjectures.LonelinessKZProductFast" if d >= 12 else
         "import Conjectures.LonelinessKZProductCertificate") + "\nimport Init.Data.RArray",
        "",
        f"/-! Integer LP-dual certificates for dimension {d}.",
        f"All {2**d} subsets are checked; no values of the real variables are sampled.",
        "Generated by scripts/generate_loneliness_kz_certificates.py. -/",
        "",
        f"namespace Loneliness.KZProduct.{name}",
        "",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0",
        "",
        f"def boundScale : ℕ := {scale}",
        f"def boundData : Array ℕ := #[{', '.join(map(str, scaled))}]",
        "def bounds (r : ℕ) : ℕ := boundData[r]?.getD 0",
        "",
    ]
    lines += data_lines(rows, d)
    lines += verification(d)
    lines += ["", f"end Loneliness.KZProduct.{name}", ""]
    output = ROOT / f"lean/Conjectures/LonelinessKZProductData{name}.lean"
    output.write_text("\n".join(lines))
    print(f"{k} speeds: {len(rows)} exact certificates, bound scale {scale}, {output.name}", flush=True)


def data_lines(rows, d, mask_offset=0, *, fast=None):
    if fast is None:
        fast = d >= 12
    # Balanced lookup and bounded assertions are also needed for dimension 8:
    # the monolithic Array proof exceeds the hosted kernel memory budget.
    def tree(lo, hi, indent):
        pad = " " * indent
        if hi-lo == 1:
            q, weights = rows[lo]
            dual = f"⟨{q}, #[{', '.join(map(str, weights))}]⟩"
            if fast:
                tails = [sum(weights[i:d]) for i in range(d+1)]
                for i in range(d):
                    assert tails[i] + (4*weights[d+i-1] if i else 0) == \
                        (q if ((mask_offset+lo) >> i)&1 else 0) + (3*weights[d+i] if i+1 < d else 0)
                dual = f"⟨{dual}, #[{', '.join(map(str, tails))}]⟩"
            return [pad + f"(.leaf {dual})"]
        mid = (lo+hi)//2
        return ([pad+f"(.branch {mid}"] + tree(lo, mid, indent+2) +
                tree(mid, hi, indent+2) + [pad+")"])
    row_type = "FastRow" if fast else "DualRow"
    definition = "noncomputable def" if fast else "def"
    return [f"{definition} rowData : Lean.RArray {row_type} :="] + tree(0, len(rows), 2)


def verification(d):
    row_def = f"noncomputable def row (m : Fin (2^{d})) : DualRow := rowData.get m.val"
    lines = ["", row_def, ""]
    if d >= 12:
        lines = ["", f"noncomputable def certificate (m : Fin (2^{d})) : FastRow := rowData.get m.val",
                 f"noncomputable def row (m : Fin (2^{d})) : DualRow := (certificate m).dual", ""]
    block_size = 64
    blocks = 2**d // block_size
    predicate = "FastValid" if d >= 12 else "DualValid"
    accessor = "certificate" if d >= 12 else "row"
    for block in range(blocks):
        lines += [f"private theorem rows_valid_block_{block} : ∀ j : Fin {block_size},",
                  f"    {predicate} {d} bounds (fun i => ({block}*{block_size}+j.val).testBit i.val)",
                  f"      ({accessor} ⟨{block}*{block_size}+j.val, by omega⟩) := by decide +kernel", ""]
    lines += [f"theorem rows_valid (m : Fin (2^{d})) :",
              f"    DualValid {d} bounds (fun i => m.val.testBit i.val) (row m) := by"]
    if d >= 12:
        lines += ["  apply fast_valid_correct bounds (fun i => m.val.testBit i.val) (certificate m)"]
    lines += [f"  let q := m.val / {block_size}",
              f"  let j : Fin {block_size} := ⟨m.val % {block_size}, Nat.mod_lt _ (by decide)⟩",
              f"  have hq : q < {blocks} := by dsimp [q]; omega",
              f"  have he : m.val = q*{block_size}+j.val := by dsimp [q,j]; omega",
              "  interval_cases q"]
    for block in range(blocks):
        lines += [f"  · have hm : m = ⟨{block}*{block_size}+j.val, by omega⟩ := Fin.ext he",
                  "    rw [hm]", f"    exact rows_valid_block_{block} j"]
    return lines


def write_partitioned_twelve(scale, scaled, rows):
    """Bound cumulative elaboration memory without changing any certificate."""
    assert len(rows) == 2048
    folder = ROOT / "lean/Conjectures"
    stem = "LonelinessKZProductDataTwelve"
    namespace = "Loneliness.KZProduct.Twelve"
    base = [
        "import Conjectures.LonelinessKZProductFast",
        "import Mathlib.Tactic.FinCases",
        "import Init.Data.RArray", "",
        "/-! Shared exact prefix bounds for the partitioned eleven-dimensional",
        "dual certificate. Generated by scripts/generate_loneliness_kz_certificates.py. -/", "",
        f"namespace {namespace}", "",
        f"def boundScale : ℕ := {scale}",
        f"def boundData : Array ℕ := #[{', '.join(map(str, scaled))}]",
        "def bounds (r : ℕ) : ℕ := boundData[r]?.getD 0", "",
        "noncomputable def assembleCertificate (blocks : Fin 8 → Fin 256 → FastRow)",
        "    (m : Fin (2^11)) : FastRow :=",
        "  blocks ⟨m.val / 256, by omega⟩ ⟨m.val % 256, Nat.mod_lt _ (by decide)⟩", "",
        "theorem assemble_valid (blocks : Fin 8 → Fin 256 → FastRow)",
        "    (hblocks : ∀ b m, FastValid 11 bounds",
        "      (fun i => (b.val*256+m.val).testBit i.val) (blocks b m))",
        "    (m : Fin (2^11)) :",
        "    FastValid 11 bounds (fun i => m.val.testBit i.val) (assembleCertificate blocks m) := by",
        "  let q : Fin 8 := ⟨m.val / 256, by omega⟩",
        "  let j : Fin 256 := ⟨m.val % 256, Nat.mod_lt _ (by decide)⟩",
        "  have he : q.val*256+j.val = m.val := by dsimp [q,j]; omega",
        "  change FastValid 11 bounds (fun i => m.val.testBit i.val) (blocks q j)",
        "  simpa only [he] using hblocks q j", "",
        f"end {namespace}", "",
    ]
    (folder / f"{stem}Base.lean").write_text("\n".join(base))
    for block in range(8):
        name = f"Block{block:02d}"
        offset = 256*block
        lines = [
            f"import Conjectures.{stem}Base", "",
            f"/-! Exact dual certificates for masks {offset} through {offset+255}.",
            "Generated by scripts/generate_loneliness_kz_certificates.py. -/", "",
            f"namespace {namespace}.{name}", "",
            "set_option maxRecDepth 100000",
            "set_option maxHeartbeats 0", "",
        ]
        lines += data_lines(rows[offset:offset+256], 11, mask_offset=offset, fast=True)
        lines += ["", "noncomputable def certificate (m : Fin 256) : FastRow := rowData.get m.val", ""]
        for part in range(4):
            lines += [f"private theorem rows_valid_block_{part} : ∀ j : Fin 64,",
                      f"    FastValid 11 bounds (fun i => ({offset}+({part}*64+j.val)).testBit i.val)",
                      f"      (certificate ⟨{part}*64+j.val, by omega⟩) := by decide +kernel", ""]
        lines += ["theorem rows_valid (m : Fin 256) :",
                  f"    FastValid 11 bounds (fun i => ({offset}+m.val).testBit i.val) (certificate m) := by",
                  "  let q := m.val / 64",
                  "  let j : Fin 64 := ⟨m.val % 64, Nat.mod_lt _ (by decide)⟩",
                  "  have hq : q < 4 := by dsimp [q]; omega",
                  "  have he : m.val = q*64+j.val := by dsimp [q,j]; omega",
                  "  interval_cases q"]
        for part in range(4):
            lines += [f"  · have hm : m = ⟨{part}*64+j.val, by omega⟩ := Fin.ext he",
                      "    rw [hm]", f"    exact rows_valid_block_{part} j"]
        lines += ["", f"end {namespace}.{name}", ""]
        (folder / f"{stem}{name}.lean").write_text("\n".join(lines))

    lines = [f"import Conjectures.{stem}Block{block:02d}" for block in range(8)]
    lines += ["", "/-! All 2048 eleven-dimensional subset certificates, assembled from",
              "eight independently checked blocks. No real variables are sampled.",
              "Generated by scripts/generate_loneliness_kz_certificates.py. -/", "",
              f"namespace {namespace}", "",
              "set_option maxRecDepth 100000", "set_option maxHeartbeats 0", "",
              "noncomputable def blockCertificate (b : Fin 8) (m : Fin 256) : FastRow :=",
              "  match b.val with"]
    for block in range(8):
        lines += [f"  | {block} => Block{block:02d}.certificate m"]
    lines += ["  | _ => default", "",
              "private theorem block_valid (b : Fin 8) (m : Fin 256) :",
              "    FastValid 11 bounds (fun i => (b.val*256+m.val).testBit i.val)",
              "      (blockCertificate b m) := by",
              "  fin_cases b"]
    for block in range(8):
        lines += ["  · simpa only [blockCertificate, Fin.val_mk] using",
                  f"      Block{block:02d}.rows_valid m"]
    lines += ["", "noncomputable def certificate (m : Fin (2^11)) : FastRow :=",
              "  assembleCertificate blockCertificate m", "",
              "noncomputable def row (m : Fin (2^11)) : DualRow := (certificate m).dual", "",
              "theorem rows_valid (m : Fin (2^11)) :",
              "    DualValid 11 bounds (fun i => m.val.testBit i.val) (row m) := by",
              "  apply fast_valid_correct bounds (fun i => m.val.testBit i.val) (certificate m)",
              "  exact assemble_valid blockCertificate block_valid m"]
    lines += ["", f"end {namespace}", ""]
    (folder / f"{stem}.lean").write_text("\n".join(lines))



