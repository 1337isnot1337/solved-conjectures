#!/usr/bin/env python3
"""Assemble checked support fragments into the actual five-runner prime theorem.

Every generated root uses the existing finite-set support semantics. The final
theorem covers every normalized minimum pair, including roots with fewer than
three available candidates. It retains the four-runner bound and avoidance
of this prime. The final theorem joins the five concrete prime certificates.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def root_assembly(data: dict, root: dict, block_size: int) -> str:
    p, b, width = data["p"], root["b"], data["width"]
    base = f"Conjectures.LonelinessFiveRunnerPrime{p:04d}"
    module = base + f"B{b:03d}"
    ns = f"Loneliness.Modular.FiveRunner.Prime{p:04d}.B{b:03d}"
    count, root_index = len(root["frames"]), root["root_index"]
    initial = root["initial"]
    fuel, index, slots = initial["fuel"], initial["index"], initial["slots"]
    selected, available, uncovered = [initial[key] for key in
                                      ("selected", "available", "uncovered")]
    if not count or root_index != count - 1 or index != root_index:
        raise ValueError("Expected the complete final root frame")
    if initial != root["frames"][root_index] or slots != 3:
        raise ValueError("Initial root state differs")
    cuts = "SupportSearch.Bits.Cuts"
    blocks = list(range(0, count, block_size))
    lines = [f"import {module}Checks{block:03d}" for block in range(len(blocks))]
    lines += ["import Lean.Elab.Tactic.Omega", "",
              f"/-! Complete support certificate for prime {p}, minimum pair {b}.",
              "Generated by scripts/generate_five_runner_assembly.py.",
              "The final theorem uses the original finite-set search predicate. -/", "",
              f"namespace {ns}", "",
              f"theorem table_checks (index : ℕ) (hi : index < {count}) :",
              f"    {cuts}.boundedCheck coverMask compatibleMask terminal lookup frames index 3",
              "      (fragments index) (frames index) = true := by"]
    if len(blocks) == 1:
        lines += ["  exact block000_checked ⟨index, hi⟩"]
    else:
        for block, start in enumerate(blocks):
            last = block == len(blocks) - 1
            if not last:
                lines += [f"  by_cases h{block} : index < {start + block_size}"]
            pad = "  " if last else "  · "
            if block == 0:
                lines += [f"{pad}exact block000_checked ⟨index, h0⟩"]
            else:
                lines += [f"{pad}have hshift : index - {start} + {start} = index := by omega"]
                indent = "  " if last else "    "
                lines += [f"{indent}simpa only [hshift] using",
                          f"{indent}  (block{block:03d}_checked ⟨index - {start}, by omega⟩)"]
    lines += ["",
              f"theorem all_frames_checked (index : ℕ) (hi : index < {count}) :",
              f"    {cuts}.Frame.Checked coverMask compatibleMask terminal lookup (frames index) :=",
              f"  {cuts}.table_sound coverMask compatibleMask terminal lookup frames fragments",
              f"    {count} 3 table_checks index hi", "",
              f"theorem root_frame_eq : frames {root_index} = rootFrame := by",
              "  decide +kernel", "",
              "theorem root_tape_checked :",
              f"    SupportSearch.Bits.tapeCheck coverMask compatibleMask terminal lookup {fuel} {index}",
              f"      {selected} {available} {uncovered} {slots} = true := by",
              f"  have h := all_frames_checked {root_index} (by decide)",
              "  rw [root_frame_eq] at h", "  exact h", "",
              "theorem tape_checked :",
              f"    SupportSearch.Bits.tapeCheck (InitialMemo.cover 6 {p} coverTable)",
              f"      (InitialMemo.compatible {p} inverse {width} compatibleTable {b})",
              f"      terminal lookup {fuel} {index}",
              f"      (InitialBits.encode (InitialSupport.selected {b}))",
              f"      (InitialBits.encode (InitialSupport.available {p} inverse {b}))",
              f"      (InitialBits.encode (InitialSupport.uncovered 6 {p} {b})) {slots} = true := by",
              "  rw [selected_mask_checked, available_mask_checked, uncovered_mask_checked]",
              "  exact root_tape_checked", "",
              "theorem root_checked :",
              f"    SupportSearch.check (InitialSupport.badTimes 6 {p})",
              f"      (InitialSupport.pairCompatible {p} inverse {b}) terminal tree",
              f"      (InitialSupport.selected {b}) (InitialSupport.available {p} inverse {b})",
              f"      (InitialSupport.uncovered 6 {p} {b}) {slots} = true := by",
              f"  exact InitialMemo.checked_tree 6 {p} inverse {width} (by decide)",
              f"    coverTable compatibleTable cover_checked compatible_checked {b}",
              f"    terminal lookup {fuel} {index} {slots} tape_checked", "",
              f"end {ns}", ""]
    return "\n".join(lines)



def prime_assembly(data: dict) -> str:
    p, half = data["p"], data["half"]
    base = f"Conjectures.LonelinessFiveRunnerPrime{p:04d}"
    ns = f"Loneliness.Modular.FiveRunner.Prime{p:04d}"
    roots = data["roots"]
    if [root["b"] for root in roots] != list(range(2, half + 1)):
        raise ValueError("Full-prime assembly requires every normalized minimum pair")
    lines = [f"import {base}B{root['b']:03d}" for root in roots]
    lines += ["import Mathlib.Tactic.IntervalCases", "",
              f"/-! Complete support classification at prime {p}.",
              "All normalized minimum pairs and supports of size at most five are covered.",
              "The only remaining runner hypothesis is the four-runner lower bound. -/", "",
              f"namespace {ns}", "", "noncomputable section", "",
              "def trees : ℕ → SupportSearch.Tree"]
    lines += [f"  | {root['b']} => B{root['b']:03d}.tree" for root in roots]
    lines += ["  | _ => B002.tree", "",
              f"theorem initial_checked (b : ℕ) (hb : 2 ≤ b) (hbound : 2 * b ≤ {p}) :",
              f"    SupportSearch.check (InitialSupport.badTimes 6 {p})",
              f"      (InitialSupport.pairCompatible {p} inverse b) terminal (trees b)",
              f"      (InitialSupport.selected b) (InitialSupport.available {p} inverse b)",
              f"      (InitialSupport.uncovered 6 {p} b) 3 = true := by",
              f"  have hbupper : b ≤ {half} := by omega", "  interval_cases b"]
    lines += [f"  · exact B{root['b']:03d}.root_checked" for root in roots]
    lines += ["",
              "/-- Actual primitive speeds, with this prime's numerical checks discharged. -/",
              "theorem primitive_classification",
              "    (hLRC : CoordinateSubspace.LonelyRunnerBound 4)",
              "    (v : Fin 5 → ℕ) (hpositive : ∀ i, 0 < v i)",
              "    (hprimitive : Search.Primitive v)",
              f"    (hmod : ∀ i, v i % {p} ≠ 0)",
              "    (hlow : value (List.ofFn v) ≤ (1 / 6 : ℝ)) :",
              "    ∃ ds ∈ FiveRunner.directions, (List.ofFn v).Perm ds := by",
              f"  exact FiveRunner.checked_prime_classification {p} (by decide) (by decide)",
              "    hLRC inverse inverse_valid rows rows_valid trees initial_checked",
              "    v hpositive hprimitive hmod hlow", "",
              "theorem primitive_classification_cases",
              "    (hLRC : CoordinateSubspace.LonelyRunnerBound 4)",
              "    (v : Fin 5 → ℕ) (hpositive : ∀ i, 0 < v i)",
              "    (hprimitive : Search.Primitive v)",
              f"    (hmod : ∀ i, v i % {p} ≠ 0)",
              "    (hlow : value (List.ofFn v) ≤ (1 / 6 : ℝ)) :",
              "    (List.ofFn v).Perm FiveRunner.consecutive ∨",
              "      (List.ofFn v).Perm FiveRunner.exceptional :=",
              "  (FiveRunner.classified_iff _).mp",
              "    (primitive_classification hLRC v hpositive hprimitive hmod hlow)",
              "", "end", f"end {ns}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", type=Path, required=True)
    parser.add_argument("--lean-dir", type=Path, default=ROOT / "lean")
    parser.add_argument("--block-size", type=int, default=32)
    parser.add_argument("--only-b", type=int)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.block_size <= 0:
        raise ValueError("Block size must be positive")
    data = json.loads(args.json.read_text())
    if data["schema"] != "five-runner-prime-support-v1":
        raise ValueError("Unexpected numerical input schema")
    p = data["p"]
    files = {}
    for root in data["roots"]:
        if args.only_b is None or args.only_b == root["b"]:
            files[f"Conjectures.LonelinessFiveRunnerPrime{p:04d}B{root['b']:03d}"] = (
                root_assembly(data, root, args.block_size))
    complete = args.only_b is None and [root["b"] for root in data["roots"]] == list(
        range(2, data["half"] + 1))
    if complete:
        files[f"Conjectures.LonelinessFiveRunnerPrime{p:04d}"] = prime_assembly(data)
    if not files:
        raise ValueError("No matching minimum pair")
    hashes = {}
    for module, content in files.items():
        path = args.lean_dir / (module.replace(".", "/") + ".lean")
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise ValueError("Generated source differs: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        hashes[module] = hashlib.sha256(content.encode()).hexdigest()
    print(json.dumps({"schema": "five-runner-prime-assembly-v1", "prime": p,
                      "full_prime_source_emitted": complete,
                      "minimum_pairs": [root["b"] for root in data["roots"]],
                      "generated_sha256": hashes}, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
